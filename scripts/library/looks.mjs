/**
 * Writes the distinct looks of each kind of control, as measured by the card scan, for the
 * looks page (/library/looks): src/library/inventory/looks.generated.ts.
 *
 *   node scripts/library/looks.mjs
 *
 * A look is the type size, the corners, the left and top padding, the border and (for the
 * controls that do not grow with their words) the height. The width and, for a text area, the
 * height follow the words and are not part of a look.
 */
import { writeFileSync } from "node:fs";
import { build } from "../catalogue/build.mjs";

const db = await build(".");
const GROWS = new Set(["text area", "label"]);
const types = db.prepare("select distinct type from observations where kind = 'control' order by type").all().map(r => r.type);
const looks = [];
for (const type of types) {
    // A date cell is its input (class date-cell-input, counted as a text box by the scan) inside a wrapper: its look is the input's.
    const rows = db.prepare("select cls, h, w, font, weight, radius, padL, padT, border, fill, system, page, path from observations where kind = 'control' and type = ?").all(type === 'date cell' ? 'text box' : type).filter(r => (type === 'date cell') === r.cls.includes('date-cell-input'));
    if (type === 'date cell' && rows.length === 0) continue;
    const groups = new Map();
    for (const r of rows) {
        const key = [r.font, r.weight, r.radius, r.padL, r.padT, r.border, GROWS.has(type) ? "" : r.h].join("|");
        const g = groups.get(key) ?? { type, font: r.font, weight: r.weight, radius: r.radius, padL: r.padL, padT: r.padT, border: r.border, height: GROWS.has(type) ? null : r.h, count: 0, classes: new Map(), places: new Map(), wMin: r.w, wMax: r.w, hMin: r.h, hMax: r.h };
        g.count++;
        g.classes.set(r.cls, (g.classes.get(r.cls) ?? 0) + 1);
        const place = r.system.replace(" System", "") + " / " + r.page + (r.path ? " / " + r.path : "");
        g.places.set(place, (g.places.get(place) ?? 0) + 1);
        g.wMin = Math.min(g.wMin, r.w); g.wMax = Math.max(g.wMax, r.w); g.hMin = Math.min(g.hMin, r.h); g.hMax = Math.max(g.hMax, r.h);
        groups.set(key, g);
    }
    for (const g of [...groups.values()].sort((a, b) => b.count - a.count)) {
        looks.push({ ...g, classes: [...g.classes].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([c, n]) => c + " x" + n), places: [...g.places].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([p]) => p) });
    }
}
const body = [
    "// Generated by scripts/library/looks.mjs from the card scan (catalogue/scans). Do not edit by hand.",
    "export interface Look { type: string; font: number; weight: string; radius: string; padL: number; padT: number; border: number; height: number | null; count: number; classes: string[]; places: string[]; wMin: number; wMax: number; hMin: number; hMax: number }",
    "",
    "export const looks: readonly Look[] = " + JSON.stringify(looks, null, 1) + ";",
    ""
].join("\n");
writeFileSync("src/library/inventory/looks.generated.ts", body);
const summary = {};
for (const l of looks) summary[l.type] = (summary[l.type] ?? 0) + 1;
console.log("looks " + looks.length + " " + JSON.stringify(summary));
