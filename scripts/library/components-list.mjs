/**
 * Writes the list of the components (docs/design/14-components-list.md) in a form that is easy to read: one table
 * to scan in which every asset is followed directly by its variants, then one block per component with its facts
 * grouped under titles (Size, Text, Shape, Spacing, Reaction, Use), one fact per line, a label before every value,
 * full words (Height, Width) and the unit after every number, and its variants directly under it. The layout
 * follows Baymard's finding on spec sheets (group the specs under subheadings, a single column of label and
 * value) and DITA's properties model (property, value, description).
 *
 *   node scripts/library/components-list.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "../catalogue/build.mjs";
import { library } from "../../src/library/data/library.ts";
import { EXTRA, fieldsOf as fieldsIn, heightText, widthText, textSize, corner, sizeOf, variantSizeOf } from "./specs.mjs";

const file = "docs/design/14-components-list.md";
const db = await build(".");
const fieldsOf = code => fieldsIn(db, code);
const out = [];
const say = (...lines) => out.push(...lines);

/** What happens under the pointer and the keyboard, in words (measured: docs/design/06-catalogue-record.md). */
const REACTION = {
    "BTN.001": "Hover and focus: the box fills with its colour and the symbol turns light.",
    "BTN.002": "Hover and focus: the circle fills with its colour and the i turns light.",
    "BTN.003": "Hover and focus: the text turns blue.",
    "BTN.004": "Not read yet.",
    "DRP.001": "Hover: the inset edge glows. Focus: a blue ring. In use: the glow and a wire in the contrast colour.",
    "TIK.001": "Hover: a blue ring inside the box. Focus: the browser's outline.",
    "TXT.001": "Hover: the inset edge glows. Focus: a blue ring. While typing: the glow and a wire in the contrast colour. A number box: no change under the pointer.",
    "LST.001": "Like the holders: the edge glows under the pointer, a blue ring on focus; Enter opens the next row.",
    "DAT.001": "The calendar button fills with a light blue and takes a blue border on hover.",
    "DAT.002": "Not read yet.",
    "DIV.001": "None.",
    "LBL.001": "None.",
    "TTL.001": "None, except the card title: it is a link (underlined and bolder under the pointer and the focus).",
    "LNK.001": "Underlined and bolder under the pointer and the focus.",
    "HLP.001": "None.",
    "ARW.001": "Hover and focus: the arrow grows 1.2 times; focus adds a 2 px blue outline.",
    "ARW.002": "Outline at rest; filled under the pointer and the focus.",
    "BUL.001": "Default, hover, selected: the bullet changes colour or opacity with the card's colour; the selected bullet is larger."
};
/** Where the scan found each asset or variant (a condition on the scan's records). */
const FOUND = {
    "BTN.DLT.001.001": "type = 'x'", "BTN.ADD.001.002": "type = 'plus' and cls like '%plus-box%'", "BTN.002": "type = 'info'",
    "BTN.004": "type = 'plus' and cls like '%strategy-add-button%'", "DRP.001": "type = 'dropdown'", "TIK.001": "type = 'tick box'",
    "TXT.BOX.001.001": "type = 'text box' and cls not like '%date-cell-input%'",
    "TXT.ARE.001.002": "type = 'text area' and (cls like '%business-foundation-note%' or cls like '%legal-entity-note%' or cls like '%brand-image-note%' or cls = 'interview-input')",
    "TXT.NAM.001.003": "type = 'text area' and (cls like '%card-name-input%' or cls like '%suggested-input%')",
    "TXT.WHL.001.004": "type = 'number box'",
    "LST.001": "type = 'text area' and cls like '%numbered-list-input%'", "DAT.001": "type = 'text box' and cls like '%date-cell-input%'", "LBL.001": "type = 'label'",
    "ARW.002": "type = 'fold arrow'", "ARW.LAB.002.001": "type = 'label arrow' and h = 24", "ARW.TTL.002.002": "type = 'label arrow' and h = 28"
};
const whereFound = code => {
    if (!FOUND[code]) return null;
    const rows = db.prepare("select system, page, count(*) n from observations where kind = 'control' and " + FOUND[code] + " group by system, page order by n desc").all();
    if (!rows.length) return null;
    const total = rows.reduce((s, r) => s + r.n, 0);
    return total + " in all: " + rows.map(r => r.system.replace(" System", "") + ", " + r.page + " " + r.n).join("; ");
};

const groupOf = new Map(library.families.flatMap(f => f.groups.map(g => [g.code, { family: f, group: g }])));
const order = library.families.flatMap(f => f.groups.map(g => g.code));
const components = library.assets.filter(a => a.category === "component" || a.group).sort((x, y) => order.indexOf(x.group) - order.indexOf(y.group));
const rows = [];
for (const a of components) {
    if (a.look) rows.push({ code: a.code, name: a.name, l: a.look });
    for (const v of a.variants) if (v.look) rows.push({ code: v.code, name: a.name + ", " + v.name, l: v.look });
}

say("# The components", "",
    "Generated by `node scripts/library/components-list.mjs` from the library. Do not edit by hand. " + components.length + " components in " + library.families.length + " families. Height and Width are in pixels (px); A look is the most used one measured, after the owner's decisions of 2026-10-15 (docs/design/13-component-defaults.md). Every variant stands directly under its asset. Each component and variant says what kind it is (a cell you fill in, a text you read, a button that acts), where it is placed, and which fields use it.", "",
    "## At a glance", "",
    "| Code | Name | Kind | Height | Width | Text size |", "|---|---|---|---|---|---|");
let lastGroup = "";
for (const a of components) {
    const home = groupOf.get(a.group);
    if (home.group.code !== lastGroup) { lastGroup = home.group.code; say("| **" + home.family.name + " / " + home.group.name + "** | | | | | |"); }
    const s = sizeOf(a);
    say("| " + a.code + " | **" + a.name + "** | " + (a.kind ?? "") + " | " + s.height + " | " + s.width + " | " + s.text + " |");
    for (const v of a.variants) {
        const vs = variantSizeOf(a, v);
        say("| ↳ " + v.code + " | " + v.name + " | " + (v.kind ?? "") + " | " + vs.height + " | " + vs.width + " | " + vs.text + " |");
    }
}
say("");

const measured = existsSync("catalogue/measures/measure-quillfield-1920.json") ? JSON.parse(readFileSync("catalogue/measures/measure-quillfield-1920.json", "utf8")) : { texts: [] };
const SCALE = [[14, "--font-small", "list text, summaries, tool words, hints, verification"], [18, "--font-body", "tile titles, card names, labels, cells, links, help text, Back"], [24, "--font-h3", "section headings, dialog titles, the guiding question"], [28, "--font-h2", "chapter and column titles"], [36, "--font-h1", "the page title and the system title"]];
const usedBy = size => rows.filter(r => r.l.fontSize === size).map(r => r.code);
say("## Text sizes and the hierarchy", "", "The five sizes of the type scale (docs/ai/layout-rules.md) against what was measured: every visible text of every page of the Identity, Brand, Business and Strategy systems at 1920 px (" + measured.texts.length + " texts, catalogue/measures/measure-quillfield-1920.json).", "",
    "| Size | Token | Role | Texts measured | Classes seen most | Components that use it |", "|---|---|---|---|---|---|");
for (const [size, token, role] of SCALE) {
    const hits = measured.texts.filter(t => t.size === size);
    const classes = {};
    for (const t of hits) classes[t.cls || t.tag] = (classes[t.cls || t.tag] ?? 0) + 1;
    const top = Object.entries(classes).sort((x, y) => y[1] - x[1]).slice(0, 3).map(([c, n]) => c + " " + n).join("; ");
    const by = usedBy(size);
    say("| " + size + " px | " + token + " | " + role + " | " + hits.length + " | " + top + " | " + (by.length > 14 ? by.slice(0, 14).join(", ") + " and " + (by.length - 14) + " more" : by.join(", ")) + " |");
}
const onScale = new Set(SCALE.map(x => x[0]));
const off = measured.texts.filter(t => !onScale.has(t.size));
const offBy = {};
for (const t of off) { const k = t.size + " px: " + (t.cls || t.tag) + " (" + t.text.slice(0, 16) + ")"; offBy[k] = (offBy[k] ?? 0) + 1; }
say("", "**Off the scale:** " + (off.length ? Object.entries(offBy).map(([k, n]) => k + " x" + n).join("; ") : "none") + ". The two 30 px texts are the typeface specimens of the Brand page (the sample of a font shown in its own size); the 0 px are the glyph of the page arrow (an icon, not read as text); the 24 px arrow is a symbol. The side panel handles were measured at 16 px earlier (the browser default, off the scale): flagged for the owner.");
const offLooks = rows.filter(r => r.l.fontSize && !onScale.has(r.l.fontSize)).map(r => r.code + " " + r.l.fontSize + " px");
say("", "**Components with a text size off the scale:** " + (offLooks.length ? offLooks.join("; ") : "none") + ".", "");

const parts = existsSync("catalogue/measures/parts-quillfield-1920.json") ? JSON.parse(readFileSync("catalogue/measures/parts-quillfield-1920.json", "utf8")) : { fonts: [], pressable: [], tags: [], images: [], units: [] };
// the fonts
const fonts = {};
for (const p of parts.fonts) for (const [k, v] of Object.entries(p.fonts)) fonts[k] = (fonts[k] ?? 0) + v;
say("## Fonts", "", "Measured on " + parts.fonts.length + " pages: " + Object.entries(fonts).sort((x, y) => y[1] - x[1]).map(([k, v]) => k + " " + v + " texts").join("; ") + ". The app's font is Inter (docs/ai/layout-rules.md). Manrope and Source Sans 3 are the Brand page's typeface specimens. Arial is the browser's default for a button that does not inherit the font: the page arrow glyph, the fold arrows and the Expand all button of the Business page, so they are not in Inter.", "");

// the defaults that exist in the app
const none = components.filter(a => a.look && !a.look.found).map(a => a.code + " " + a.name);
say("## Defaults that exist in the app", "", "A default look is the most used one measured, so it should exist somewhere in the app. " + (components.filter(a => a.look).length - none.length) + " of " + components.filter(a => a.look).length + " defaults were found in the example organisation. **Not found:** " + (none.length ? none.join("; ") : "none") + ".", "");

// the text styles: every text read, by its expression
const measuredTexts = measured.texts.filter(t => !t.holder);
const styles = new Map();
for (const t of measuredTexts) {
    const key = [t.size + " px", t.weight, t.italic ? "italic" : "", t.underline ? "underlined" : "", t.transform === "uppercase" ? "capitals" : ""].filter(Boolean).join(", ");
    const e = styles.get(key) ?? { n: 0, cls: {} };
    e.n++; e.cls[t.cls || t.tag] = (e.cls[t.cls || t.tag] ?? 0) + 1;
    styles.set(key, e);
}
say("## Text styles: the presentation of every text read (analysis)", "", "The texts of the readers (labels, titles, links, help texts, messages) could be one component, the text, with variants by **presentation** only (size, weight, capitals, italics, underline), and the purpose given in the field. Measured: " + styles.size + " different presentations cover all " + measuredTexts.length + " texts of the four systems; the first five cover " + Math.round([...styles.values()].sort((x, y) => y.n - x.n).slice(0, 5).reduce((s2, e) => s2 + e.n, 0) / measuredTexts.length * 100) + "%. Not yet in the library: it waits for the owner's decision.", "",
    "| Presentation | Texts | Classes seen most |", "|---|---|---|");
for (const [k, e] of [...styles].sort((x, y) => y[1].n - x[1].n)) say("| " + k + " | " + e.n + " | " + Object.entries(e.cls).sort((x, y) => y[1] - x[1]).slice(0, 3).map(([c, n]) => c + " " + n).join("; ") + " |");
say("");

// the texts that can be pressed
const pressed = new Map();
for (const p of parts.pressable) {
    const key = [p.size + " px", p.weight, p.italic ? "italic" : "", p.underline ? "underlined" : "", p.transform === "uppercase" ? "capitals" : "", p.cls || p.tag].filter(Boolean).join(", ");
    pressed.set(key, (pressed.get(key) ?? 0) + 1);
}
say("## Texts that can be pressed (analysis of the gap in the links)", "", "Every text that is a link, a button or has a pointer cursor, with its presentation. The library has three links (underlined, blue, symbol); the app has many more pressable texts. " + parts.pressable.length + " found on " + parts.fonts.length + " pages.", "", "| Presentation and class | Found |", "|---|---|");
for (const [k, n] of [...pressed].sort((x, y) => y[1] - x[1]).slice(0, 30)) say("| " + k + " | " + n + " |");
say("");

let lastFamily = "";
lastGroup = "";
for (const a of components) {
    const home = groupOf.get(a.group);
    if (home.family.code !== lastFamily) {
        lastFamily = home.family.code;
        say("## " + home.family.name, "", home.family.description, "", "**What every component of this family has**", ...home.family.characteristics.map(c => "- " + c), "");
    }
    if (home.group.code !== lastGroup) {
        lastGroup = home.group.code;
        say("### " + home.group.name + " (" + home.group.code + ")", "", home.group.description, "", "**What every component of this group has, besides the family's**", ...home.group.characteristics.map(c => "- " + c), "");
    }
    say("#### " + a.code + " " + a.name[0].toUpperCase() + a.name.slice(1), "", a.summary, "");
    say("**Kind and place**", "- Kind: " + (a.kind ?? ""), ...(a.belongs ? ["- Placed in: " + a.belongs] : []), ...(fieldsOf(a.code) ? ["- Fields: " + fieldsOf(a.code)] : []), "");
    const ex = EXTRA[a.code];
    if (a.look) {
        const l = a.look;
        say("**Size**", "- Height: " + heightText(l, a.code), "- Width: " + widthText(l, a.code), "",
            "**Text**", "- Size: " + textSize(l), "- Weight: " + l.fontWeight, "",
            "**Shape**", "- Corners: " + corner(l), "- Border: " + l.border + " px", "",
            "**Spacing**", "- Padding left: " + l.paddingLeft + " px", "- Padding top: " + l.paddingTop + " px", "");
    } else if (ex) say("**Size**", "- Height: " + ex.height, "- Width: " + ex.width, "- Source: " + ex.note, "");
    if (REACTION[a.code]) say("**Reaction**", "- " + REACTION[a.code], "");
    const here = whereFound(a.code);
    if (a.look?.found || here) say("**Use**", "- Found: " + (here ?? a.look.found + " times in the example organisation"), ...(a.look?.places ? ["- Places in the app: " + a.look.places + " (distinct pages and classes; the count of the UI, not of the example)"] : []), "");
    if (a.variants.length) {
        say("**Variants**", "");
        for (const v of a.variants) {
            const vs = variantSizeOf(a, v);
            say("##### " + v.code + " " + v.name, "", v.description, "", "- Kind: " + (v.kind ?? a.kind ?? ""), "- Placed in: " + (v.belongs ?? a.belongs ?? ""), ...(fieldsOf(v.code) ? ["- Fields: " + fieldsOf(v.code)] : []), "- What changes: " + v.edits,
                "- Height: " + vs.height, "- Width: " + vs.width, "- Text size: " + vs.text);
            const l = v.look ?? a.look;
            if (l) say("- Border: " + l.border + " px; Padding left: " + l.paddingLeft + " px; Padding top: " + l.paddingTop + " px");
            const w = whereFound(v.code);
            if (w) say("- Found: " + w);
            say("");
        }
    }
    if (a.requires.length) say("**Built from**", ...a.requires.map(r => "- " + (r.variant ?? r.asset) + ": " + r.role), "");
}

const text = out.join("\n") + "\n";
if (process.argv.includes("--check")) {
    const now = existsSync(file) ? readFileSync(file, "utf8").split("\r").join("") : "";
    if (now !== text) { console.error("out of date: " + file); process.exit(1); }
    console.log("the components list is up to date");
} else { writeFileSync(file, text); console.log("wrote " + file + " (" + out.length + " lines)"); }
