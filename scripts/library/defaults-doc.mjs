/**
 * Writes the component defaults document (docs/design/13-component-defaults.md): the default look of each
 * component and variant (the most used one measured), the looks merged into it and the looks kept for the
 * owner, each default checked against the text hierarchy of the app (14, 18, 24, 28, 36) and against the
 * target sizes of WCAG 2.2 (24px minimum, 44px enhanced), with the sources.
 *
 *   node scripts/library/defaults-doc.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { library } from "../../src/library/data/library.ts";

const file = "docs/design/13-component-defaults.md";
const out = [];
const say = (...lines) => out.push(...lines);
const cell = value => String(value ?? "").replace(/\|/g, "/").replace(/\s+/g, " ").trim();

say("# Component defaults", "",
    "Generated by `node scripts/library/defaults-doc.mjs` from the library. Do not edit by hand. Criteria of the owner (2026-10-15): where one look is used far more than the others (the others fewer than 5 uses or 5 percent, within 2px) the most used look is the default and the others are merged into it; a look above 5 percent or more than 2px away is kept and left to the owner; the x takes the look with the most uses and the plus takes the plus that matches it; the text holders (free text, list line, name cell, text box) are separate and each has its own default; every default is checked against the text hierarchy of the app and the target sizes of WCAG 2.2.", "");

say("## Reference sizes", "",
    "| Measure | Value | Source | How sure |", "|---|---|---|---|",
    "| Target size, minimum (level AA) | 24 by 24 CSS pixels, with five exceptions (spacing, equivalent control, inline, user agent, essential) | [W3C, Understanding SC 2.5.8](https://www.w3.org/WAI/WCAG22/Understanding/target-size-minimum.html) | Read from the W3C page |",
    "| Target size, enhanced (level AAA) | 44 by 44 CSS pixels | [W3C, Understanding SC 2.5.5](https://w3.org/WAI/WCAG22/Understanding/target-size-enhanced.html) | Stated by the W3C page found by search; the page body was not read directly |",
    "| Touch target, Material | at least 48 by 48 dp, 8dp between targets | [Material Design, applying density](https://material.io/design/layout/applying-density.html) | A search summary of the older material.io page; the current M3 pages did not load |",
    "| Touch target, Apple | 44 by 44 points | secondary summaries (for example [uxcel](https://app.uxcel.com/courses/mobile-design/ios-app-design-712/minimum-tap-target-size-8996)); the Apple page did not load | Not read from Apple |",
    "| Touch target, physical | 1cm by 1cm | [Nielsen Norman Group](https://www.nngroup.com/articles/touch-target-size/) | A search summary; the article gives no pixel value |",
    "| Text input height | 40px (Carbon medium, default; 32 small, 48 large); USWDS 2.5rem (40px) | [IBM Carbon, text input](https://carbondesignsystem.com/components/text-input/usage/); USWDS compiled CSS | Carbon from its documentation; USWDS from compiled CSS |",
    "| Text field height, Material | 56dp (Compose default) | developer reports, not the M3 specification | Weak; check m3.material.io |",
    "| Text hierarchy of this app | 14 small, 18 body, 24 h3, 28 h2, 36 h1 | docs/ai/layout-rules.md, Title sizes | The app's own rule |", "",
    "The measured controls of this app are 44 to 45px high (text inputs), 32px (x and plus), 22px (the i) and 18px (the tick box): the text inputs are above the 40px of the design systems; the 18px tick box and the 22px i are under the 24px minimum.", "");

say("## Defaults, component by component", "",
    "| Asset | Variant | Height | Type | Hierarchy | Corners | Padding left/top | Border | Found | Target (WCAG 2.5.8, 24px) |", "|---|---|---|---|---|---|---|---|---|---|");
const rows = [];
for (const a of library.assets) {
    if (a.look) rows.push([a.code + " " + a.name, "(asset)", a.look]);
    for (const v of a.variants) if (v.look) rows.push([a.code + " " + a.name, v.code + " " + v.name, v.look]);
}
const targetOf = (name, look) => {
    if (look.height === null) return "follows the words (a field, not a button)";
    if (/box button|info|fold arrow|tick/.test(name)) return look.height >= 44 ? "meets 44" : look.height >= 24 ? "meets 24" : "under 24: needs the spacing exception";
    return look.height >= 24 ? "meets 24" : "under 24";
};
for (const [asset, variant, look] of rows) say("| " + cell(asset) + " | " + cell(variant) + " | " + (look.height ?? "words") + " | " + look.fontSize + " | " + look.scale + " | " + look.corners + " | " + look.paddingLeft + "/" + look.paddingTop + " | " + look.border + " | " + look.found + " | " + targetOf(asset, look) + " |");
say("");

say("## Text holders", "",
    "Separated by purpose; each has its own default look.", "",
    "| Holder | Variant | What it is | Look |", "|---|---|---|---|");
const txt = library.assets.find(a => a.code === "TXT.001");
for (const v of txt.variants) say("| text input | " + v.code + " " + v.name + " | " + cell(v.description) + " | " + (v.look ? "height " + (v.look.height ?? "words") + ", type " + v.look.fontSize + ", corners " + v.look.corners + ", padding " + v.look.paddingLeft + "/" + v.look.paddingTop + ", border " + v.look.border + ", found " + v.look.found : "none") + " |");
const lst = library.assets.find(a => a.code === "LST.001");
for (const v of lst.variants) say("| list | " + v.code + " " + v.name + " | " + cell(v.description) + " | built from the list line |");
say("");

say("## Looks merged and looks kept", "");
for (const a of library.assets.filter(x => x.lookNotes?.length)) {
    say("### " + a.code + " " + a.name, "");
    for (const n of a.lookNotes) say("- " + n);
    say("");
}

say("## Outside the text hierarchy", "");
const off = rows.filter(([, , l]) => l.scale.startsWith("off"));
say(off.length ? off.map(([asset, variant, l]) => "- " + asset + " " + variant + ": " + l.scale + " (" + l.found + " found). The other text controls use 18, the body size.").join("\n") : "None.", "");

const text = out.join("\n") + "\n";
if (process.argv.includes("--check")) {
    const now = existsSync(file) ? readFileSync(file, "utf8").split("\r").join("") : "";
    if (now !== text) { console.error("out of date: " + file); process.exit(1); }
    console.log("the defaults document is up to date");
} else { writeFileSync(file, text); console.log("wrote " + file + " (" + out.length + " lines)"); }
