/**
 * The Frequency options of the cost cards: the default (the seven of every master tile), the options of each category and group, and of each
 * cost option (billing type), compared with the default. Writes docs/design/18-frequency-options.md.
 *
 *   npx vite-node scripts/catalogue/frequency-options.mjs
 */
import { writeFileSync } from "node:fs";
import {
    BUSINESS_COST_FREQUENCIES, BUSINESS_RESOURCE_GROUPS, BUSINESS_OFFERING_RESOURCE_GROUPS, BUSINESS_PARTNER_GROUPS,
    frequencyIdsOf, costOptionsOf, optionFrequenciesOf, STRATEGY_METRIC_FREQUENCIES
} from "../../src/framework/engine/AnswerUtils.ts";
import { LEGAL_ENTITY_EXPENSE_FREQUENCIES } from "../../src/framework/engine/LegalEntityJurisdictions.ts";
import { COST_FREQUENCIES } from "../../src/framework/engine/FinancialModel.ts";

const label = id => BUSINESS_COST_FREQUENCIES.find(entry => entry.id === id)?.label ?? id;
const all = BUSINESS_COST_FREQUENCIES.map(entry => entry.id);
const list = ids => ids.map(label).join(", ");
const verdict = ids => ids.length === all.length ? "same as the default" : "**" + (all.length - ids.length) + " fewer** (no " + all.filter(id => !ids.includes(id)).map(label).join(", ") + ")";

const out = [
    "# The Frequency options",
    "",
    "Generated by `npx vite-node scripts/catalogue/frequency-options.mjs` from the code (`BUSINESS_COST_FREQUENCIES`, the groups' lists in `AnswerUtils.ts`). Do not edit by hand.",
    "",
    "## The default",
    "",
    "The Frequency of a cost card (Resources, Partners & Suppliers, Delivery's Resources: Quantity, Price, currency, Frequency) offers **" + list(all) + "** (seven). A group the lists do not know offers all seven. A group with one frequency shows it as text; a One-time one is not shown.",
    "",
    "Other lists that are not this one:",
    "",
    "| Where | Options |",
    "|---|---|",
    "| Legal expense (Cost, Frequency) | " + LEGAL_ENTITY_EXPENSE_FREQUENCIES.join(", ") + " |",
    "| Strategy Metric (Frequency) | " + STRATEGY_METRIC_FREQUENCIES.join(", ") + " |",
    "| Financial model (forecast lines) | " + COST_FREQUENCIES.map(entry => entry.label).join(", ") + " |",
    "| Founder (Salary, Frequency) | Monthly, Annually (and the others its card offers: see the Founders card) |",
    "",
    "## By category and group (what each offers against the default seven)",
    ""
];
const row = (place, group, kind) => {
    const ids = frequencyIdsOf(place, kind.id);
    return "| " + place + " | " + group + " | " + kind.label + " | " + list(ids) + " | " + verdict(ids) + " |";
};
out.push("| Master tile | Category | Group | Frequencies offered | Against the default |", "|---|---|---|---|---|");
for (const group of BUSINESS_RESOURCE_GROUPS) for (const kind of group.kinds) out.push(row("infrastructure", group.label, kind));
for (const group of BUSINESS_OFFERING_RESOURCE_GROUPS) for (const kind of group.kinds) out.push(row("offering", group.label, kind));
for (const place of ["infrastructure", "offering"]) for (const side of ["partners", "suppliers"]) for (const group of BUSINESS_PARTNER_GROUPS[place][side]) {
    const ids = frequencyIdsOf(place, group.id);
    out.push("| " + place + " | " + (side === "partners" ? "Partners" : "Suppliers") + " | " + group.label + " | " + list(ids) + " | " + verdict(ids) + " |");
}
out.push("", "## By cost option (the billing type an option sets limits the frequency again)", "", "| Master tile | Group | Option | Billing | Frequencies | Against the group |", "|---|---|---|---|---|---|");
for (const place of ["infrastructure", "offering"]) {
    const groups = place === "infrastructure" ? BUSINESS_RESOURCE_GROUPS : BUSINESS_OFFERING_RESOURCE_GROUPS;
    for (const group of groups) for (const kind of group.kinds) {
        for (const option of costOptionsOf(place, kind.id) ?? []) {
            const own = optionFrequenciesOf(place, kind.id, option.id);
            if (!own) continue;
            const offered = frequencyIdsOf(place, kind.id);
            const missing = own.filter(id => !offered.includes(id));
            out.push("| " + place + " | " + kind.label + " | " + option.label + " | " + (option.billing || "-") + " | " + list(own) + " | " + (missing.length ? "**" + list(missing) + " is not offered by the group**" : own.length === offered.length ? "same as the group" : "fewer than the group") + " |");
        }
    }
}
out.push("");
out.push("## The rules (2026-10-19)", "",
    "1. **A card offers only what its group offers.** A frequency kept from another group, or set before the group was chosen, that the group does not offer is not listed: the card takes the group's first frequency (a group with one has it as text).",
    "2. **A card with no group yet offers what the groups of its master tile offer, together** (Infrastructure's or Offering's), never one no group of it has.",
    "3. **Per hour is a Per unit with the unit hour.** Every team group offers Monthly and Per hour: Admin Team (Infrastructure) now as Delivery Team (Offering) does.",
    "",
    "## Proposed (to decide)", "",
    "| Related groups | Today | Proposal |",
    "|---|---|---|",
    "| Insurances: Infrastructure / Offering | Annually, Monthly / Annually, Per project | Both: Annually, Monthly, Per project (a policy can be paid monthly in both) |",
    "| Certificates: Infrastructure / Offering | One-time, Annually / Per project, Annually | Both: One-time, Annually, Per project |",
    "| Licences: Infrastructure / Offering | One-time, Annually, Per unit (both) | none: consistent |",
    "| Contractors & Advisers (Offering) / Technical Support (Infrastructure) | Per project, Per hour / Per project, Per unit (visit, hour), Annually | Add Per hour to both by their units |",
    "| Business Services, Creative & IT Services (Infrastructure Suppliers) | Monthly, Annually, Per project / Per project, Monthly | Add Per hour to both (consultants bill by the hour) |",
    "| Tickets & Trip Costs | Per unit, Per project (both) | none: consistent |",
    "");
writeFileSync("docs/design/18-frequency-options.md", out.join("\n"));
console.log("wrote docs/design/18-frequency-options.md");
