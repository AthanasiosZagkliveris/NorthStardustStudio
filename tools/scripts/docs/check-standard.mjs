/* Checks the standard of the documents (docs/standard.md): npm run docs:standard. Exits 1 with the list of what does not meet it. */
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
const R = fileURLToPath(new URL("../../../", import.meta.url));
const KINDS = ["rules", "reference", "research", "collection", "current design", "specification", "proposal", "living list", "log", "playbook", "index", "contents", "archive", "generated"];

function walk(dir, out = []) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(p, out); else if (p.endsWith(".md")) out.push(p);
    }
    return out;
}
const problems = [];
const files = walk(R + "docs").map(f => path.relative(R, f).replace(/\\/g, "/"));
const numbers = [];
for (const f of files) {
    const lines = readFileSync(R + f, "utf8").replace(/\r\n/g, "\n").split("\n");
    const head = lines.slice(0, 8);
    const isDesign = /^docs\/design\/[a-z]+\/\d\d-/.test(f);
    const isReadme = /(^|\/)README\.md$/.test(f) && f !== "docs/design/README.md";
    // 1. the title
    if (!/^# \S/.test(lines[0])) problems.push(f + ": the first line is not a title");
    if (isDesign) {
        const nn = +/\/(\d\d)-/.exec(f)[1];
        numbers.push(nn);
        const t = /^# (\d+)\. /.exec(lines[0]);
        if (!t || +t[1] !== nn) problems.push(f + ": the title must begin \"# " + nn + ". \" (the number of the file)");
    }
    // 2. the status line or the Generated by line
    const status = head.find(l => l.startsWith("Status:"));
    const generated = head.some(l => l.startsWith("Generated by"));
    if (!status && !generated) { if (f !== "docs/README.md" && f !== "docs/index.md") problems.push(f + ": no \"Status:\" line (or \"Generated by\" line) in the first lines"); continue; }
    if (status) {
        const kind = /^Status: \*\*([^*]+)\*\*/.exec(status);
        if (!kind) problems.push(f + ": the status line does not begin \"Status: **kind**\"");
        else if (!KINDS.includes(kind[1].toLowerCase())) problems.push(f + ": unknown kind \"" + kind[1] + "\" (the kinds are in docs/standard.md)");
        if (!/\d{4}-\d{2}-\d{2}/.test(status)) problems.push(f + ": the status line has no date (YYYY-MM-DD)");
    }
}
// 3. numbering without a gap or a repeat
numbers.sort((a, b) => a - b);
for (let n = 1; n <= numbers[numbers.length - 1]; n++) if (!numbers.includes(n)) problems.push("docs/design: no document is numbered " + n);
for (let i = 1; i < numbers.length; i++) if (numbers[i] === numbers[i - 1]) problems.push("docs/design: the number " + numbers[i] + " is used twice");
// 4. relative links resolve
for (const f of files) {
    const text = readFileSync(R + f, "utf8");
    for (const m of text.matchAll(/\]\(([^)\s#]+)(#[^)]*)?\)/g)) {
        if (/^(https?:|mailto:)/.test(m[1])) continue;
        if (!existsSync(path.resolve(path.dirname(R + f), decodeURI(m[1])))) problems.push(f + ": broken link " + m[1]);
    }
}
if (problems.length) { console.error("The documents do not meet docs/standard.md:\n" + problems.map(p => "  " + p).join("\n")); process.exit(1); }
console.log("The " + files.length + " documents meet docs/standard.md (" + numbers.length + " numbered design documents, 1 to " + numbers[numbers.length - 1] + ").");
