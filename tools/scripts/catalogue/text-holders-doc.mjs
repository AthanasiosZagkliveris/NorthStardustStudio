/**
 * Writes docs/design/17-text-holders.md and exports/The-text-holders.csv from tools/catalogue/measures/text-holders.json
 * (written by tools/scripts/catalogue/text-holders.mjs).
 *
 *   node tools/scripts/catalogue/text-holders-doc.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const { rows } = JSON.parse(readFileSync("tools/catalogue/measures/text-holders.json", "utf8"));
const place = scene => scene.replace(/ \/ page$/, "");
const defaultRows = row => row.kind === "text field" ? "1" : String(row.minLines ?? row.rowsAttr);
const cells = rows.map(row => ({
    where: place(row.scenes[0]) + (row.scenes.length > 1 ? " (+" + (row.scenes.length - 1) + " more)" : ""),
    surface: row.where, kind: row.kind, label: row.label || "-", name: row.aria || "-", cls: row.cls || "-", placeholder: row.placeholder || "-",
    size: row.size, w: row.w, h: row.h, def: defaultRows(row), filled: row.filledLines ?? "empty in the example", chars: row.filled ? row.chars : ""
}));

const by = new Map();
for (const row of rows) {
    const key = row.kind + " | " + (row.cls || "-");
    if (!by.has(key)) by.set(key, []);
    by.get(key).push(row);
}
const range = list => list.length ? (Math.min(...list) === Math.max(...list) ? String(list[0]) : Math.min(...list) + " to " + Math.max(...list)) : "-";
const summary = [...by].sort((a, b) => b[1].length - a[1].length).map(([key, list]) => {
    const [kind, cls] = key.split(" | ");
    return "| " + kind + " | `" + cls + "` | " + list.length + " | " + range(list.map(row => row.size)) + " | " + range(list.map(row => Number(defaultRows(row)))) + " | " + range(list.filter(row => row.filledLines).map(row => row.filledLines)) + " | " + range(list.map(row => row.w)) + " |";
});
const areas = rows.filter(row => row.kind === "text area").length;
const md = [
    "# The text holders",
    "",
    "Generated by `node tools/scripts/catalogue/text-holders-doc.mjs` from the walk of the running app (`tools/scripts/catalogue/text-holders.mjs`, the Quillfield example organization, the light theme, a 1920px window). Do not edit by hand.",
    "",
    "A text holder here is a text area or a text field that is **not** a name cell, a number, a date, a colour or a search box. **" + rows.length + "** were found: " + areas + " text areas and " + (rows.length - areas) + " text fields.",
    "",
    "What was covered: every page of the four Foundation systems, every master tile opened, the first two nested tiles (cards) of each opened view, the Global Settings page, and the Notes panel with a new note (a note is a date cell and a text; the calendar panel component is not on any page yet, so it holds no holder). Cards beyond the first two of a view, and fields that appear only after a tick, are not in this list.",
    "",
    "\"Default rows\" is the number of lines the holder opens with when empty (the minimum height in lines); \"rows with the example\" is the number of lines the example organization's text fills (the holder grows to it); a holder the example leaves empty says so.",
    "",
    "## By kind and style",
    "",
    "| Kind | Style (class) | How many | Type size (px) | Default rows | Rows with the example | Width (px) |",
    "|---|---|---|---|---|---|---|",
    ...summary,
    "",
    "## Every holder",
    "",
    "| Where | Surface | Kind | Label | Name (accessible) | Style | Size px (type, w x h) | Default rows | Rows with the example | Characters |",
    "|---|---|---|---|---|---|---|---|---|---|",
    ...cells.map(c => "| " + [c.where, c.surface, c.kind, c.label, c.name, "`" + c.cls + "`", c.size + ", " + c.w + " x " + c.h, c.def, c.filled, c.chars].join(" | ").replace(/\n/g, " ") + " |"),
    ""
].join("\n");
writeFileSync("docs/design/17-text-holders.md", md);
const csv = ["Where;Surface;Kind;Label;Name;Style;Placeholder;Type size;Width;Height;Default rows;Rows with the example;Characters",
    ...cells.map(c => [c.where, c.surface, c.kind, c.label, c.name, c.cls, c.placeholder, c.size, c.w, c.h, c.def, c.filled, c.chars].map(v => '"' + String(v).replace(/"/g, '""') + '"').join(";"))].join("\r\n");
mkdirSync("exports", { recursive: true });
writeFileSync("exports/The-text-holders.csv", "﻿" + csv);
console.log("wrote docs/design/17-text-holders.md and exports/The-text-holders.csv (" + rows.length + " holders)");
