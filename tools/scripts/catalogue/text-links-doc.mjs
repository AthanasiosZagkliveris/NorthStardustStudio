/**
 * The list of every text link and where it appears: for each link class (src/components/interview/fields/textLinks.ts) the places in the code that draw it
 * (file and line) and what it does, and the links the walk of the app found on a page (tools/catalogue/measures/link-survey.json). Writes
 * docs/design/current/19-text-links.md and exports/The-text-links.csv.
 *
 *   node tools/scripts/catalogue/text-links-doc.mjs
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const WHAT = {
    "business-engagement-link": ["Link in a Business page", "Opens or does something on another place: a Segment's Offering or Profile on the Foundation page, \"Show as table\", \"Review the costs on Financial Foundation\", \"Refresh\", a Funding line's source, a Metric's link."],
    "channel-resource-open": ["Channel resource name", "In the Customer Channel's resources table: opens the resource's card on 3. Infrastructure & Capability."],
    "notepad-text-button": ["Text button of a note or a channel action", "In the Notes panel and in the channel actions (\"# Link an action\", \"shared action\"): a text that acts."],
    "legal-entity-name-link": ["Card title that is a link", "A Legal expense or requirement whose name is a link to the card it was made from (in the card's head)."],
    "business-capability-link": ["Related card line", "The name in a card's \"R. / A. / P. / S.\" line: opens the related Resource, Activity, Partner or Supplier card with this one."],
    "business-capability-child-name": ["Name that is a link to its parent card", "The head of a card another card made (an Activity made by a Resource's status, a Customer Channel's card): its name opens the card that made it."],
    "business-capability-responsibility-link": ["A founder's responsibility", "In a founder's Responsibilities and Completed lists: opens the Activity's card under the founder's."]
};

const walk = dir => readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
});
const files = walk("src/components").filter(file => /\.tsx$/.test(file) && !/\.test\./.test(file));
const classes = Object.keys(WHAT);
const places = new Map(classes.map(name => [name, []]));
for (const file of files) {
    const lines = readFileSync(file, "utf8").split(/\r?\n/);
    lines.forEach((line, index) => {
        for (const name of classes) {
            if (new RegExp("className=[^>]*\\b" + name + "\\b").test(line) || new RegExp("[\"'`]" + name + "[\"'`]").test(line)) {
                places.get(name).push({ file: file.replace(/\\/g, "/"), line: index + 1 });
            }
        }
    });
}

const survey = existsSync("tools/catalogue/measures/link-survey.json") ? JSON.parse(readFileSync("tools/catalogue/measures/link-survey.json", "utf8")).rows : [];
const out = [
    "# 19. The text links",
    "",
    "Generated by `node tools/scripts/catalogue/text-links-doc.mjs` from the code and the walk of the app. Do not edit by hand.",
    "",
    "A text link is a piece of text that acts when pressed: it opens a card, a page or a list, or does something. All of them are drawn by ONE component (`TextLink.tsx`) and have one look (`src/styles/text-links.css`, the classes listed in `src/components/interview/fields/textLinks.ts`): the default blue, regular, the letter spacing of a bold, no underline; under the pointer or the keyboard bold and underlined (the line 1px under the descenders); on one row, a longer text moving right to left under the pointer to be read whole. In a completed card they are grey until the pointer is on them.",
    "",
    "The link symbol (a drawn chain beside a chosen dropdown name) and the kind letters (R., A., P., S.) are not text links: the symbol is a button in the card's tone, 20% larger under the pointer.",
    "",
    "## The kinds, and where the code draws them",
    "",
    "| Class | What it is | What it does | Where in the code (file:line) |",
    "|---|---|---|---|"
];
const csv = ["Class;Kind;What it does;Files"];
for (const name of classes) {
    const where = places.get(name);
    out.push("| `" + name + "` | " + WHAT[name][0] + " | " + WHAT[name][1] + " | " + (where.map(place => place.file.replace("src/components/", "") + ":" + place.line).join(", ") || "-") + " |");
    csv.push([name, WHAT[name][0], WHAT[name][1], where.map(place => place.file.replace("src/components/", "") + ":" + place.line).join(" ")].map(value => '"' + value.replace(/"/g, '""') + '"').join(";"));
}
out.push("", "## The links the walk of the app found on a page", "", "The walk opens every page of the four systems, every master tile and the first two cards of each view (the Quillfield example), so a link that appears only in a later card is not in this table: the table above is the complete list of kinds.", "", "| Where | Link (text) | Kind | Colour | Weight |", "|---|---|---|---|---|");
for (const row of survey) {
    out.push("| " + row.scenes[0].replace(/ \/ page$/, "") + " | " + row.text + " | `" + (row.cls || row.tag) + "` | " + row.colour + " | " + row.weight + " |");
}
out.push("");
writeFileSync("docs/design/current/19-text-links.md", out.join("\n"));
mkdirSync("exports", { recursive: true });
writeFileSync("exports/The-text-links.csv", "﻿" + csv.join("\r\n"));
console.log("wrote docs/design/current/19-text-links.md and exports/The-text-links.csv");
