/**
 * Writes docs/design/23-help-texts.md and exports/The-help-texts.csv from tools/catalogue/measures/help-texts.json
 * (written by tools/scripts/catalogue/help-texts.mjs): every "i" help text, by category (a system's page) and group (the tile it stands in),
 * with its rows (the lines its panel fills at the width it opens in) and its characters. Read-only: the texts are written in the code.
 *
 *   node tools/scripts/catalogue/help-texts-doc.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const { rows } = JSON.parse(readFileSync("tools/catalogue/measures/help-texts.json", "utf8"));
const cell = text => String(text).replace(/\|/g, "/").replace(/\s*\n\s*/g, " ").trim();
const where = row => {
    const parts = row.scenes[0].split(" / ");
    const category = parts[0] === "Global Settings" ? "Global Settings" : parts[0] + " / " + (parts[1] === "main" ? "main page" : parts[1]);
    const group = (parts.find(part => part.startsWith("tile ")) ?? "the page itself").replace(/^tile /, "");
    return { category, group };
};
const list = rows.map(row => ({ ...row, ...where(row), text: cell(row.text) }))
    .sort((a, b) => a.category.localeCompare(b.category) || a.group.localeCompare(b.group) || a.label.localeCompare(b.label) || a.place.localeCompare(b.place));

const range = values => values.length ? (Math.min(...values) === Math.max(...values) ? String(values[0]) : Math.min(...values) + " to " + Math.max(...values)) : "-";
const byCategory = new Map();
for (const row of list) {
    if (!byCategory.has(row.category)) byCategory.set(row.category, []);
    byCategory.get(row.category).push(row);
}
const byPlace = new Map();
for (const row of list) {
    if (!byPlace.has(row.place)) byPlace.set(row.place, []);
    byPlace.get(row.place).push(row);
}

const md = [
    "# The help texts",
    "",
    "Generated by `node tools/scripts/catalogue/help-texts-doc.mjs` from the walk of the running app (`tools/scripts/catalogue/help-texts.mjs`: the Quillfield example, 1920px). Do not edit by hand. A read-only list: the texts are written in the code (the `info` and `note` lists of each editor and the framework's Help).",
    "",
    "A help text is what the round \"i\" button opens. **" + list.length + "** were found. \"Rows\" is the number of lines the panel fills at the width it opens in (a tile dialog's panel 480px, a floating card's 360px, as found); \"Points\" is the number of lines or sentences in it; \"Characters\" counts the whole text.",
    "",
    "What was covered: every page of the four systems, every master tile opened, the first two cards of each view, Global Settings. A help text that appears only in a later card, or after a tick, is not here.",
    "",
    "## By category",
    "",
    "| Category (system / page) | Help texts | Rows | Characters |",
    "|---|---|---|---|",
    ...[...byCategory].map(([name, items]) => "| " + name + " | " + items.length + " | " + range(items.map(r => r.lines)) + " | " + range(items.map(r => r.chars)) + " |"),
    "",
    "## By where it opens",
    "",
    "| Opens in | Help texts | Rows | Characters |",
    "|---|---|---|---|",
    ...[...byPlace].map(([name, items]) => "| " + name + " | " + items.length + " | " + range(items.map(r => r.lines)) + " | " + range(items.map(r => r.chars)) + " |"),
    "",
    "## Every help text, by category and group",
    ""
];
for (const [category, items] of byCategory) {
    md.push("### " + category, "");
    const groups = new Map();
    for (const row of items) {
        if (!groups.has(row.group)) groups.set(row.group, []);
        groups.get(row.group).push(row);
    }
    for (const [group, inside] of groups) {
        md.push("**" + group + "**", "", "| Label | Opens in | Rows | Points | Characters | Text |", "|---|---|---|---|---|---|");
        for (const row of inside) md.push("| " + cell(row.label) + " | " + row.place + " | " + row.lines + " | " + row.points + " | " + row.chars + " | " + row.text.slice(0, 160) + (row.text.length > 160 ? "..." : "") + " |");
        md.push("");
    }
}
writeFileSync("docs/design/23-help-texts.md", md.join("\n"));

const quote = value => '"' + String(value).replace(/"/g, '""') + '"';
mkdirSync("exports", { recursive: true });
writeFileSync("exports/The-help-texts.csv", "﻿" + [["Category", "Group", "Label", "Opens in", "Rows", "Points", "Characters", "Text"].join(","), ...list.map(row => [row.category, row.group, row.label, row.place, row.lines, row.points, row.chars, row.text].map(quote).join(","))].join("\r\n"));
console.log(list.length + " help texts -> docs/design/23-help-texts.md, exports/The-help-texts.csv");
