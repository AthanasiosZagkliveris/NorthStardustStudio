const addProbe = JSON.parse((await import("node:fs")).readFileSync("tools/catalogue/probes/add-probe-quillfield-1920-light.json", "utf8")).records.filter(r => r.choice === "master tile");

const cleanChapter = raw => {
    let title = (raw || "").trim();
    const extras = [];
    if (title.startsWith("▾")) { extras.push("fold arrow"); title = title.slice(1); }
    if (extras.length && /[a-z]i$/.test(title)) { extras.push("info (i)"); title = title.slice(0, -1); }
    title = title.replace(/^(\d+)\.(\S)/, "$1. $2");
    return { title: title || "(no title)", extras: extras.join(", ") };
};

const pageRows = [];
let pageNo = 0;
for (const [sid, system, number] of SYSTEMS) {
    for (const p of pages.filter(x => x.system === system)) {
        pageNo++;
        const id = pad("P", pageNo, 2);
        const mine = addProbe.filter(r => r.system.startsWith(system.split(" ")[0]) && r.page === p.page);
        const chapters = [...new Set(mine.map(r => r.chapter))];
        const frames = all("select distinct json_extract(data, '$.label') l from observations where system = ? and page = ? and type = 'chapter frame' and path = ''", system, p.page).map(x => x.l).filter(Boolean);
        const type = mine.length ? "tiles page (chapters of master tiles)" : "inline cards page (cards on the page, no master tiles)";
        pageRows.push({ id, system: sid, name: p.page, type, chapters: chapters.length || frames.length, master_tiles: mine.length, system_name: system, number });
    }
}
