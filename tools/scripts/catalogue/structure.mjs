import { existsSync, readFileSync, writeFileSync } from "node:fs";

const check = process.argv.includes("--check");
let stale = 0;
/** Writes a generated file, or in --check mode compares it with the file on disk. */
function put(path, content) {
    if (!check) { writeFileSync(path, content); return; }
    const now = existsSync(path) ? readFileSync(path, "utf8").split("\r").join("") : "";
    if (now !== content) { stale++; console.error("out of date: " + path); }
}
