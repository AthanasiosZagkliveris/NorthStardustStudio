const say = (...lines) => out.push(...lines);
const cell = value => String(value ?? "").replace(/\|/g, "/").replace(/\s+/g, " ").trim();
function table(title, note, rows, columns) {
    store.push({ code: title.split(". ")[0], title: title.replace(/^[A-Z]+. /, ""), note: note || "", columns: columns ?? (rows[0] ? Object.keys(rows[0]) : []), rows: rows.map(r => Object.fromEntries(Object.entries(r).map(([k, v]) => [k, typeof v === "number" ? v : String(v ?? "")]))) });
    say("### " + title, "");
    if (note) say(note, "");
    if (!rows.length) { say("(nothing recorded)", ""); return; }
    const keys = columns ?? Object.keys(rows[0]);
    say("| " + keys.join(" | ") + " |", "|" + keys.map(() => "---").join("|") + "|");
    for (const row of rows) say("| " + keys.map(key => cell(row[key])).join(" | ") + " |");
    say("");
}
