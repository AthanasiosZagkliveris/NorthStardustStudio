/**
 * Writes the assets library as a document (docs/design/09-assets-library.md) from src/library/data.
 *
 *   node tools/scripts/library/generate-library-doc.mjs [--check]
 *
 * --check compares the document with the library and fails if it is out of date.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { library } from "../../../src/library/data/library.ts";
import { placements } from "../../../src/library/data/placements.ts";
import { KINDS } from "../../../src/library/model/types.ts";

const file = "docs/design/09-assets-library.md";
const cell = value => String(value ?? "").replace(/\|/g, "/").replace(/\s+/g, " ").trim();
const out = [];
const say = (...lines) => out.push(...lines);

say("# The assets library", "",
    "Generated by `node tools/scripts/library/generate-library-doc.mjs` from the library (src/library/data/library.ts). Do not edit by hand: the library is changed by the procedure of document 08 (check, library, library log, inventory, placement, app log).", "",
    library.assets.length + " assets, " + library.assets.reduce((n, a) => n + a.variants.length, 0) + " variants, " + library.variables.length + " variables, " + placements.length + " placements. Codes: an asset is three capital letters and a number (BTN.001); a variant adds its letters and numbers (BTN.DLT.001.001); a variant is an edited version of its asset.", "");

say("## Kinds", "", "| Letters | Kind | Category | Assets |", "|---|---|---|---|");
for (const [letters, kind] of Object.entries(KINDS)) say("| " + letters + " | " + kind.name + " | " + kind.category + " | " + library.assets.filter(a => a.code.startsWith(letters + ".")).length + " |");
say("");

say("## Variables", "");
for (const v of library.variables) {
    say("### " + v.code + " " + v.name, "", v.description, "", "| Value | Meaning |", "|---|---|");
    for (const value of v.values) say("| " + cell(value.name) + " | " + cell(value.description) + " |");
    say("");
}

const count = new Map();
for (const p of placements) count.set(p.asset, (count.get(p.asset) ?? 0) + 1);
for (const category of ["component", "tile", "frame", "card", "field"]) {
    const mine = library.assets.filter(a => a.category === category);
    say("## " + category[0].toUpperCase() + category.slice(1) + " assets (" + mine.length + ")", "");
    if (category === "field") {
        say("| Code | Name | Variables | Requires | Placements | Catalogue |", "|---|---|---|---|---|---|");
        for (const a of mine) say("| " + a.code + " | " + cell(a.name) + " | " + a.variables.join(", ") + " | " + a.requires.map(r => (r.variant ?? r.asset) + " (" + r.role + ")").join("; ") + " | " + (count.get(a.code) ?? 0) + " | " + a.catalogue.join(", ") + " |");
        say("");
        continue;
    }
    for (const a of mine) {
        say("### " + a.code + " " + a.name, "", a.summary, "");
        say("- **Variables:** " + (a.variables.join(", ") || "none"));
        const lookText = l => (l.height !== null ? "height " + l.height + (l.width ? ", width " + l.width : "") + ", " : l.minHeight ? "height at least " + l.minHeight + ", " : "") + "type " + l.fontSize + " (" + l.scale + "), corners " + l.corners + ", padding " + l.paddingLeft + "/" + l.paddingTop + ", border " + l.border + ", found " + l.found;
        if (a.look) say("- **Default look:** " + lookText(a.look));
        for (const n of a.lookNotes ?? []) say("  - " + n);
        if (a.contracts?.length) say("- **Measured contract:** " + a.contracts.join(", "));
        if (a.catalogue.length) say("- **Catalogue:** " + a.catalogue.join(", "));
        if (count.get(a.code)) say("- **Placements:** " + count.get(a.code));
        if (a.requires.length) say("- **Requires:** " + a.requires.map(r => (r.variant ?? r.asset) + " (" + r.role + ")").join("; "));
        say("");
        if (a.variants.length) {
            say("| Variant | Name | Edits in the main asset | Own parts | Default look |", "|---|---|---|---|---|");
            for (const v of a.variants) say("| " + v.code + " | " + cell(v.name) + " | " + cell(v.edits) + " | " + (v.requires ?? []).map(r => r.asset).join(", ") + " | " + (v.look ? lookText(v.look) : "") + " |");
            say("");
        }
    }
}

const text = out.join("\n") + "\n";
if (process.argv.includes("--check")) {
    const now = existsSync(file) ? readFileSync(file, "utf8").split("\r").join("") : "";
    if (now !== text) { console.error("out of date: " + file + " (run npm run library:doc)"); process.exit(1); }
    console.log("the library document is up to date");
} else {
    writeFileSync(file, text);
    console.log("wrote " + file + " (" + out.length + " lines)");
}
