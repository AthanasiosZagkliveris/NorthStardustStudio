/**
 * The owner's reorganisation of the text components, 2026-10-15, applied to the library once (a migration, kept
 * as the record; the changes are then logged with npm run library:log). The owner's model:
 *
 *   - What a person fills in is a holder: a text holder (a text box with fixed space, a free text that grows as
 *     you type or press Enter, a name cell on top of a card whose order number is generated automatically), a list
 *     (ONE cell that holds numbered rows divided by lines, the numbers in the cell), a number cell (only digits, no
 *     more digits than required), a date cell, a dropdown, a tick box. All of them use the body text.
 *   - What a person reads is not filled in: a label (prefilled; its size and style matter, its position belongs to
 *     the field), a title (prefilled, or generated by another input; in cards it replaces the name cell and links to
 *     the input that generates it), a link, a help text (a text that is there and is not a label or a title).
 *   - A title that is too long wraps in a master tile, moves on a tile and on a chapter, and uses one line, cut, as a
 *     link or a dropdown option in a card.
 *
 *   node tools/scripts/library/apply-decisions-8.mjs
 */
import { writeFileSync } from "node:fs";
import { library } from "../../../src/library/data/library.ts";
import { looks } from "../../../src/library/inventory/looks.generated.ts";

const DATE = "owner, 2026-10-15";
const variables = structuredClone(library.variables);
const assets = structuredClone(library.assets);
const asset = code => assets.find(a => a.code === code);
const note = (a, text) => { a.lookNotes = [...(a.lookNotes ?? []), text]; };
const L = (fontSize, fontWeight, scale, extra = {}) => ({ height: null, fontSize, fontWeight, corners: "0px", paddingLeft: 0, paddingTop: 0, border: 0, scale, found: 0, ...extra });

// ---- the variables
variables.push(
    { code: "VAR012", name: "origin", description: "Where the words of a reading text come from.", values: [{ name: "prefilled", description: "The words are written in the app." }, { name: "generated", description: "The words come from another input (a card's name, a tile that a card generates) and link to it." }] },
    { code: "VAR013", name: "long text", description: "What a text does when it is too long for its room.", values: [{ name: "wraps", description: "It continues on the next line." }, { name: "moves", description: "It stays on one line and moves horizontally." }, { name: "one line, cut", description: "It stays on one line and the rest is cut." }] },
    { code: "VAR014", name: "growth", description: "Whether a holder grows as the person writes.", values: [{ name: "grows", description: "The cell grows as you type or press Enter." }, { name: "fixed space", description: "The cell keeps the space it has." }] },
    { code: "VAR015", name: "digit limit", description: "How many digits a number cell accepts.", values: [{ name: "as required", description: "Only digits can be typed, and no more digits than the field requires; the limit is set by the field." }] }
);

// ---- the text holder: a text box, a free text, a name cell
const txt = asset("TXT.001");
txt.name = "text holder";
txt.variables = [...txt.variables.filter(c => c !== "VAR006"), "VAR014", "VAR006"];
txt.summary = "A cell the person fills in with text (letters or numbers), in the body size. A text box keeps its space; a free text grows as you type or press Enter; a name cell stands on top of a card and its order number is generated automatically. A text that is only read is not a holder (see the help text, label, title and link).";
const keep = ["TXT.BOX.001.001", "TXT.ARE.001.002", "TXT.NAM.001.003"];
txt.variants = txt.variants.filter(v => keep.includes(v.code));
const v = code => txt.variants.find(x => x.code === code);
v("TXT.BOX.001.001").description = "One line of text in a cell that keeps its space.";
v("TXT.BOX.001.001").edits = "A single line; fixed space.";
v("TXT.BOX.001.001").values = { VAR014: "fixed space" };
v("TXT.ARE.001.002").description = "A description text: the cell gets bigger as you type or press Enter (Description, Offerings, Market).";
v("TXT.ARE.001.002").edits = "Grows with the words; Enter adds a line inside it.";
v("TXT.ARE.001.002").values = { VAR014: "grows" };
v("TXT.NAM.001.003").description = "The name of a card, on top of the card. The order number is generated automatically and stands inside the cell.";
v("TXT.NAM.001.003").edits = "At the top of a card; the order number is automatic and inside the cell; it wraps and grows.";
v("TXT.NAM.001.003").values = { VAR014: "grows" };
txt.lookNotes = (txt.lookNotes ?? []).filter(n => !/list line|title input/.test(n));
note(txt, "the holders (" + DATE + "): text and number holders all use the body text (18px); their variants depend on their function. A text that is only read is not a holder.");

// ---- the list: one cell with numbered rows
const list = asset("LST.001");
list.name = "list";
list.summary = "A text that needs a list is ONE cell that holds numbered rows divided by thin lines, the numbers inside the cell (Values, Principles, SWOT points, Initiatives, Responsibilities). It grows as rows are added; Enter opens the next row; the rows can be moved and removed.";
list.variables = ["VAR001", "VAR002", "VAR003", "VAR004", "VAR006", "VAR014"];
list.variants = [];
list.requires = [];
const listLook = looks.find(l => l.type === "text area" && l.classes.some(c => c.includes("numbered-list-input")));
list.look = { height: null, minHeight: 44, fontSize: 18, fontWeight: "400", corners: "6px", paddingLeft: 12, paddingTop: 8, border: 1, scale: "body 18", found: listLook?.count ?? 129, places: listLook?.placeCount };
list.lookNotes = ["measured (the owner's description, " + DATE + "): the list is one cell, 6px corners and a 1px border; each row is at least 43 to 44px high, divided from the next by a thin line, with its number inside the cell at the left and the text wrapping; the row's own box has 8px corners and no border (inside the cell). The earlier reading, a single line with its number outside the cell, was wrong."];

// ---- the help text: a text that is there and is not a label or a title
const help = {
    code: "HLP.001", name: "help text", category: "component",
    summary: "A text that is already there and is not a label or a title: it helps, explains or shows. It is read, not filled in. Its variants follow its style.",
    variables: ["VAR003", "VAR004"], catalogue: [],
    variants: [
        { code: "HLP.INF.001.001", name: "Info text", description: "The note that the i shows (a short sentence or a few points).", edits: "Shown in a note, not in the page.", values: {} },
        { code: "HLP.BUL.001.002", name: "Bulleted list", description: "A read-only list of what something includes or holds (the list on a tile).", edits: "Bullets; small text.", values: {}, look: L(14, "400", "small 14") },
        { code: "HLP.NUM.001.003", name: "Numbered list", description: "A read-only numbered list (a founder's roles recalled from the profile).", edits: "Numbers; no cell.", values: {} },
        { code: "HLP.SUM.001.004", name: "Summary line", description: "A line that summarises a card or a tile (dates, status, price).", edits: "One short line; small and muted.", values: {}, look: L(14, "400", "small 14") },
        { code: "HLP.VAL.001.005", name: "Shown value", description: "A value the app fills in and shows beside a label (the group of a card, a total).", edits: "Plain text, not a cell.", values: {} }
    ],
    requires: [], look: L(14, "400", "small 14"),
    lookNotes: ["small text (14px) for lists, summaries and notes: the app's text hierarchy (docs/ai/layout-rules.md, Title sizes). Only the bulleted list and the summary line carry a measured look here."]
};

// ---- the title: prefilled or generated; what it does when it is too long
const T = (code, name, description, edits, look, values) => ({ code, name, description, edits, values, look });
const title = {
    code: "TTL.001", name: "title", category: "component",
    summary: "The name of a page, a chapter, a view, a box, a tile or a card, read and not filled in. A title is prefilled, or generated by another input; in a card a generated title replaces the name cell and is a link to the input that generates it. A title that is too long wraps, moves, or keeps one line and is cut, by where it stands.",
    variables: ["VAR003", "VAR004", "VAR012", "VAR013"], catalogue: [],
    variants: [
        T("TTL.PAG.001.001", "Page title", "The title of the page in the header (3. Business System, 3. Infrastructure & Capability).", "The largest title: 36px (h1).", L(36, "400", "h1 36"), { VAR012: "prefilled" }),
        T("TTL.CHP.001.002", "Chapter title", "The title of a chapter (1. Infrastructure & Capability). Every chapter has a title.", "28px (h2); a title that is too long moves horizontally.", L(28, "400", "h2 28"), { VAR012: "prefilled", VAR013: "moves" }),
        T("TTL.DLG.001.003", "Dialog title", "The title of a dialog and of a section heading (Resources / Digital Infrastructure).", "24px (h3), bold.", L(24, "700", "h3 24"), { VAR012: "prefilled" }),
        T("TTL.BOX.001.004", "Box name", "The name of the tile or box a floating card belongs to, above the card.", "24px (h3), bold; outside the card.", L(24, "700", "h3 24"), { VAR012: "prefilled" }),
        T("TTL.MTL.001.005", "Master tile title", "The title of a master tile, underlined by a rule.", "18px (body), weight 600; a long title wraps (Typography and Text Hierarchy).", L(18, "600", "body 18"), { VAR012: "prefilled", VAR013: "wraps" }),
        T("TTL.TIL.001.006", "Tile title", "The title of a tile that a floating card generates (a Resource tile); it takes the name of the input that generates it.", "18px, weight 600; generated; a long title moves horizontally.", L(18, "600", "body 18"), { VAR012: "generated", VAR013: "moves" }),
        T("TTL.CRD.001.007", "Card title", "The title in a card that replaces the name cell (a generated title): the name is a link to the input that generates it.", "18px; generated; a link to its input; one line, the rest is cut.", L(18, "600", "body 18"), { VAR012: "generated", VAR013: "one line, cut" }),
        T("TTL.OPT.001.008", "Option title", "A title as a dropdown option in a card.", "18px; generated; one line, the rest is cut.", L(18, "400", "body 18"), { VAR012: "generated", VAR013: "one line, cut" })
    ],
    requires: [], look: undefined,
    lookNotes: ["sizes from the app's text hierarchy (docs/ai/layout-rules.md, Title sizes: page 36, column 28, dialog and section 24, tile and card names 18; weight 600 on tiles and boxes, 700 on headings); not measured by the scan. The owner's rules (" + DATE + "): two categories, prefilled and generated; a title in a master tile wraps; on a tile or a chapter it moves; as a link or a dropdown option in a card it uses one line and the rest is cut."]
};
delete title.look;

// ---- the link: read, not filled in
const T2 = (code, name, description, edits, values = {}) => ({ code, name, description, edits, values });
const tileLinkAsset = asset("TIL.004");
const link = {
    code: "LNK.001", name: "link", category: "component",
    summary: "A text or a symbol that opens something: a tile, a card, a view. It is read and pressed, not filled in; its style varies with its function.",
    variables: ["VAR001", "VAR002", "VAR003", "VAR004", "VAR012"], catalogue: tileLinkAsset.catalogue,
    variants: [
        T2("LNK.TIL.001.001", "Tile link", "A link inside a master tile that opens one of the things the tile lists.", "Text inside a tile; opens a view or a card.", { VAR012: "prefilled" }),
        T2("LNK.CRD.001.002", "Card name link", "The name of a card that is a link to the card that generates it (a child's name links to its parent card): underlined, bolder under the pointer and the focus.", "Underlined; generated; opens the parent card.", { VAR012: "generated" }),
        T2("LNK.SYM.001.003", "Link symbol", "The small symbol beside a dropdown choice that shows the choice is a link to another card.", "A symbol, no words.", { VAR012: "generated" })
    ],
    requires: [], lookNotes: ["the tile link (TIL.004) is a variant of the link (" + DATE + "): labels, links and titles are read, not filled in."]
};
assets.splice(assets.findIndex(a => a.code === "TIL.004"), 1);
assets.splice(assets.findIndex(a => a.code === "LBL.001") + 1, 0, title, link, help);

// ---- the fields: the shown values are help text; SWOT points are lists
for (const a of assets) {
    for (const r of a.requires) {
        if (r.variant === "TXT.RDO.001.004") { r.asset = "HLP.001"; r.variant = "HLP.VAL.001.005"; }
    }
    if (a.category === "field" && ["Strengths", "Weaknesses", "Opportunities", "Threats"].includes(a.name)) {
        a.requires = a.requires.map(r => (r.asset === "TXT.001" ? { asset: "LST.001", role: "the list of " + a.name.toLowerCase() + " (numbered rows in one cell)" } : r));
    }
}
const chapter = asset("FRM.001");
chapter.requires = chapter.requires.map(r => (r.variant === "TXT.TTL.001.006" ? { asset: "TTL.001", variant: "TTL.CHP.001.002", role: "the title of the chapter" } : r));
asset("FRM.004").requires = [{ asset: "TTL.001", variant: "TTL.BOX.001.004", role: "the name of the tile or box" }];
asset("FRM.003").requires = [...asset("FRM.003").requires, { asset: "TTL.001", variant: "TTL.DLG.001.003", role: "the title of the dialog" }];
asset("FRM.002").requires = [...asset("FRM.002").requires, { asset: "TTL.001", variant: "TTL.PAG.001.001", role: "the title of the page" }];
asset("TIL.001").requires = [...asset("TIL.001").requires, { asset: "TTL.001", variant: "TTL.MTL.001.005", role: "the title of the tile" }, { asset: "LNK.001", variant: "LNK.TIL.001.001", role: "the links it lists" }];
asset("TIL.002").requires = [{ asset: "TTL.001", variant: "TTL.TIL.001.006", role: "the title, generated by the card" }];

for (const a of assets) for (const r of [...a.requires, ...a.variants.flatMap(x => x.requires ?? [])]) if (["TXT.LST.001.005", "TXT.TTL.001.006"].includes(r.variant)) throw new Error("a requirement still names a removed variant: " + a.code);

// ---- the number cells, the label, the date: the owner's statements
const number = asset("NUM.001");
number.variables = [...number.variables, "VAR015"];
number.summary = "A cell for a number: only digits can be typed, and no more digits than the field requires. In the body size, 44px high. The percent, years and months boxes are squares.";
note(number, "digits: by the owner's description (" + DATE + ") a number cell accepts only numbers, and no more digits than the field requires.");
const label = asset("LBL.001");
note(label, "the label is prefilled text that is read, not filled in; the layout around it is arranged in the field, so what matters here is its size and style (" + DATE + ").");

writeFileSync("src/library/data/library.ts", [
    "// The assets library, seeded once by tools/scripts/library/seed-library.mjs from the catalogue (docs/design/core/07-structure-tables.md).",
    "// From now on the library is the source: it is changed by the procedure of docs/design/library/08-library-system.md (check, library, library log, inventory, placement, app log).",
    "",
    'import type { Library } from "../model/types.ts";',
    "",
    "export const library: Library = " + JSON.stringify({ variables, assets }, null, 1) + ";",
    ""
].join("\n"));
console.log("decisions applied: " + assets.length + " assets");
