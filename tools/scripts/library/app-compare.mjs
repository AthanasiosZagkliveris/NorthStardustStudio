/**
 * The library against the app (docs/design/library/15-library-vs-app.md): for each component the library holds a look (height,
 * width, corners, line, type size); the walk of the running app (tools/scripts/catalogue/app-crawl.mjs, tools/catalogue/measures/
 * crawl-quillfield-1920.json) measured every control. This writes, per component, what the library says, what the app
 * draws (each distinct value, in how many views), and whether they agree. A size 1.1 times the library's is a tile grown
 * under the pointer or by its list (scale), not a difference.
 *
 *   node tools/scripts/library/app-compare.mjs [--check]     --check fails when a component differs and is not listed as known
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { library } from "../../../src/library/data/library.ts";

const file = "docs/design/library/15-library-vs-app.md";
const crawl = JSON.parse(readFileSync("tools/catalogue/measures/crawl-quillfield-1920.json", "utf8"));
const lookOf = code => { const a = library.assets.find(x => x.code === code); if (a) return { name: a.name, look: a.look }; for (const x of library.assets) { const v = x.variants.find(y => y.code === code); if (v) return { name: x.name + ", " + v.name, look: v.look ?? x.look }; } throw new Error("no component " + code); };

// what the app calls each component: a class of its element (the name of the control in the walk)
const ROWS = [
    ["BTN.001", "x of a card or a nested head", i => /strategy-box-remove|card-remove/.test(i.cls), { lines: [1] }],
    ["BTN.001", "x of a list row", i => /numbered-list-remove/.test(i.cls)],
    ["BTN.ADD.001.001", "plus box on a tile", i => /plus-box.*section-tile-plus/.test(i.cls)],
    ["BTN.ADD.001.001", "plus box in a card row", i => /plus-box-small/.test(i.cls)],
    ["BTN.ADD.001.001", "plus in a nested head", i => /^strategy-box-add/.test(i.cls)],
    ["BTN.SHR.001.002", "shrink (cards to tiles)", i => /strategy-box-tiles/.test(i.cls)],
    ["BTN.002", "info button (the i)", i => /info-note-button/.test(i.cls)],
    ["BTN.003", "main Back (footer)", i => /^back-link/.test(i.cls)],
    ["BTN.SEC.003.001", "Back of a carousel", i => /carousel-rail-back/.test(i.cls)],
    ["BTN.SEC.003.001", "Back of a tile view", i => /section-tile-back/.test(i.cls)],
    ["BTN.004", "wide add button, hugging", i => /^strategy-add-button$/.test(i.cls)],
    ["BTN.ROW.004.001", "wide add button, full row", i => /strategy-add-button.*list-add/.test(i.cls)],
    ["BTN.005", "add card tile", i => /add-card-tile/.test(i.cls)],
    ["BTN.006", "tool button", i => /^header-tool/.test(i.cls) && /Focus|Search|Notes|Settings|Review/.test(i.text)],
    ["BTN.008", "text toggle (Expand all)", i => /fold-all-toggle/.test(i.cls)],
    ["DRP.001", "dropdown", i => /option-picker-trigger/.test(i.cls)],
    ["TXT.001", "text box (one line)", i => i.tag === "input" && i.type === "text" && /^interview-input$|^interview-input\.(business-channel-resource-name|strategy-theme-name|delivery-number|legal-entity-column-centre)/.test(i.cls)],
    ["TXT.SQR.001.005", "square number box", i => /brand-size-input/.test(i.cls)],
    ["DAT.001", "date cell", i => /date-cell-input/.test(i.cls)],
    ["TIK.001", "tick box", i => i.tag === "input" && i.type === "checkbox", { ignore: ["type"] }],
    ["PCK.001", "colour picker", i => /brand-colour-picker/.test(i.cls)],
    ["ARW.001", "page and carousel arrow", i => /page-arrow/.test(i.cls) && i.w === 24],
    ["ARW.002", "fold arrow of a card", i => /strategy-box-toggle/.test(i.cls)],
    ["ARW.TTL.002.002", "title arrow", i => /label-arrow/.test(i.cls) && i.w > 26],
    ["LST.001", "text area inside a list cell (the cell itself, .numbered-list, is 6 px with a 1 px line)", i => /numbered-list-input/.test(i.cls), { only: ["type"] }],
    ["SYM.001", "card symbol", i => /card-tile-symbol/.test(i.cls)]
];
// what is known and decided to be applied later (the owner's proposals), so that the check lists only what is new
const KNOWN = new Set(["BTN.003|Back of a tile view", "BTN.SEC.003.001|Back of a tile view"]);

const px = n => (Math.round(n * 100) / 100) + " px";
const out = [];
const say = (...l) => out.push(...l);
const verdicts = [];
say("# 15. The library against the app", "",
    "Generated by `node tools/scripts/library/app-compare.mjs` from the library and the walk of the running app (" + crawl.scenes.length + " views: every page of the four systems, every master tile, the first two cards of each view). Do not edit by hand. For each component the library holds a look: what the library says, what the app draws, and whether they agree. A size 1.1 times the library's is a tile that has grown, not a difference. A disabled x (in a completed card) has a 1 px line, by its contract. Text weights are left out (frozen).", "",
    "| Component | Library | In the app | Views | Agrees |", "|---|---|---|---|---|");
for (const [code, label, test, options = {}] of ROWS) {
    const { name, look } = lookOf(code);
    const found = new Map();
    for (const scene of crawl.scenes) for (const i of scene.items) if (test(i)) {
        const key = i.w + " x " + i.h + ", " + i.radius + ", line " + i.border.split(" ")[0] + (i.size ? ", " + i.size + " px" : "");
        if (!found.has(key)) found.set(key, new Set());
        found.get(key).add(scene.where);
    }
    const lib = look ? [look.width ? px(look.width) : "any", look.height ? px(look.height) : "words"].join(" x ") + ", " + look.corners.replace("px", " px") + ", line " + look.border + (look.fontSize ? ", " + look.fontSize + " px" : "") : "no look";
    if (!found.size) { say("| " + code + " " + label + " | " + lib + " | not in the views walked | 0 | - |"); continue; }
    const rows = [...found].sort((a, b) => b[1].size - a[1].size);
    const problems = new Set();
    const lines = rows.map(([key, views]) => {
        const [wh, radius, line, size] = key.split(", ");
        const [w, h] = wh.split(" x ").map(Number);
        const r = parseFloat(radius), b = parseFloat(line.replace("line ", ""));
        const scaled = look?.height && Math.abs(h - look.height * 1.1) < 0.3;
        const bad = [];
        const only = options.only;
        if (!only && look?.height && !scaled && Math.abs(h - look.height) > 0.6) bad.push("height " + h + " not " + look.height);
        if (!only && look?.width && !scaled && Math.abs(w - look.width) > 0.6) bad.push("width " + w + " not " + look.width);
        if (!only && look?.corners && radius !== look.corners && !(radius === "50%" && look.corners === "50%") && Math.abs(r - parseFloat(look.corners)) > 0.1 && !look.corners.endsWith("%")) bad.push("corners " + radius + " not " + look.corners);
        if (!only && look && b !== look.border && !(options.lines ?? []).includes(b)) bad.push("line " + b + " not " + look.border);
        if (look?.fontSize && size && parseFloat(size) !== look.fontSize && !(options.ignore ?? []).includes("type")) bad.push("type " + size + " not " + look.fontSize + " px");
        for (const x of bad) problems.add(x);
        return w + " x " + h + " px, " + radius + ", line " + b + (size ? ", " + size : "") + (scaled ? " (grown 1.1)" : "") + " in " + views.size + (bad.length ? " **(" + bad.join("; ") + ")**" : "");
    });
    const known = KNOWN.has(code + "|" + label);
    verdicts.push({ code, label, ok: problems.size === 0, known });
    say("| " + code + " " + label + " | " + lib + " | " + lines.join("<br>") + " | " + new Set(rows.flatMap(([, v]) => [...v])).size + " | " + (problems.size === 0 ? "yes" : known ? "no (known)" : "**no**") + " |");
}
const bad = verdicts.filter(v => !v.ok);
say("", "**" + (verdicts.length - bad.length) + " of " + verdicts.length + " components agree.** " + (bad.length ? "Differ: " + bad.map(v => v.code + " " + v.label).join("; ") + "." : ""), "");
const text = out.join("\n") + "\n";
if (process.argv.includes("--check")) {
    const now = existsSync(file) ? readFileSync(file, "utf8").split("\r").join("") : "";
    if (now !== text) { console.error("out of date: " + file); process.exit(1); }
    const unknown = bad.filter(v => !v.known);
    if (unknown.length) { console.error("the app differs from the library: " + unknown.map(v => v.code + " " + v.label).join("; ")); process.exit(1); }
    console.log("the app agrees with the library (" + verdicts.length + " components)");
} else { writeFileSync(file, text); console.log("wrote " + file + ": " + (verdicts.length - bad.length) + " of " + verdicts.length + " components agree"); }
