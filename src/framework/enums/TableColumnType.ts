/**
 * Supported Framework table column types.
 */
export enum TableColumnType {

    /**
     * Single-line text.
     */
    Text = "text",

    /**
     * Multi-line text.
     */
    TextArea = "textarea",

    /**
     * Number.
     */
    Number = "number",

    /**
     * Date.
     */
    Date = "date",

    /**
     * Reusable Framework Field.
     */
    Field = "field"

}