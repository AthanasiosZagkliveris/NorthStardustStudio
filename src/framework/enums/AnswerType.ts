/**
 * Supported Framework answer types.
 */
export enum AnswerType {

    /**
     * Single-line text input.
     */
    Text = "text",

    /**
     * Multi-line text input.
     */
    TextArea = "textarea",

    /**
     * Numeric input.
     */
    Number = "number",

    /**
     * Date picker.
     */
    Date = "date",

    /**
     * Reusable Framework Field.
     */
    Field = "field",

    /**
     * Dynamic Framework Table.
     */
    Table = "table"

}