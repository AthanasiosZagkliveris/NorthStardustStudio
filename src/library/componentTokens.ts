import { library } from "./data/library.ts";

/**
 * The sizes of the components as the stylesheets read them: the library (src/library/data/library.ts) is the one place
 * where the height of a cell, the size of a box button or of a mark is written; src/styles/components.generated.css is
 * what it says, as custom properties, written by tools/scripts/library/component-tokens.mjs. The asset contracts of
 * src/library/assets take their sizes from here too, so a size is never written twice.
 */

export interface ComponentToken {
    token: string;
    value: string;
    code: string;
    what: string;
}

const lookOf = (code: string) => {
    const asset = library.assets.find(a => a.code === code);
    const variant = asset ? undefined : library.assets.flatMap(a => a.variants).find(v => v.code === code);
    const look = (asset ?? variant)?.look;
    if (!look) throw new Error("no look for " + code + " in the library");
    return look;
};

/** The height of a component in the library, in px. */
export const lookHeight = (code: string): number => {
    const height = lookOf(code).height;
    if (height === null) throw new Error(code + " has no fixed height in the library");
    return height;
};

/** The width of a component in the library, in px. */
export const lookWidth = (code: string): number => {
    const width = lookOf(code).width;
    if (width === undefined) throw new Error(code + " has no width in the library");
    return width;
};

const px = (n: number) => n + "px";

/** Components that share one size and must agree in the library. */
const SAME: readonly (readonly [string, readonly string[]])[] = [
    ["--size-mark", ["BTN.002", "TIK.001", "BTN.007"]],
    ["--card-cell-height", ["TXT.001", "DRP.001", "DAT.001"]],
    ["--size-box-button", ["BTN.001", "BTN.ADD.001.001"]]
];

/** The three corner steps (--radius-sm, -md, -lg): the corners of a text button, of a cell and of a tile, as the library has them. */
export function cornerSteps(): { readonly "radius-sm": number; readonly "radius-md": number; readonly "radius-lg": number } {
    const n = (code: string) => parseFloat(lookOf(code).corners);
    return { "radius-sm": n("BTN.008"), "radius-md": n("TXT.001"), "radius-lg": n("FRM.TIL.001.007") };
}

export function componentTokens(): ComponentToken[] {
    const tokens: ComponentToken[] = [
        { token: "--card-cell-height", value: px(lookHeight("TXT.001")), code: "TXT.001", what: "every single-line cell: a text box, a dropdown, a date, a name cell" },
        { token: "--control-square", value: px(lookWidth("TXT.SQR.001.005")), code: "TXT.SQR.001.005", what: "a box as wide as a cell is tall: a number with its unit beside it" },
        { token: "--box-radius", value: lookOf("TXT.001").corners, code: "TXT.001", what: "the corners of a cell" },
        { token: "--size-box-button", value: px(lookHeight("BTN.001")), code: "BTN.001", what: "the box buttons: the x, the plus, the calendar" },
        { token: "--size-mark", value: px(lookHeight("BTN.002")), code: "BTN.002", what: "the marks: the i, the tick box, the link symbol" },
        { token: "--add-button-height", value: px(lookHeight("BTN.004")), code: "BTN.004", what: "the wide add button" },
        { token: "--tool-button-height", value: px(lookHeight("BTN.006")), code: "BTN.006", what: "a tool button of the header" },
        { token: "--logo-holder-width", value: px(lookWidth("IMG.LOG.001.001")), code: "IMG.LOG.001.001", what: "the Logo holder at its widest: it scales down with its card, never past this" },
        { token: "--logo-holder-ratio", value: lookWidth("IMG.LOG.001.001") + " / " + lookHeight("IMG.LOG.001.001"), code: "IMG.LOG.001.001", what: "the Logo holder's width to height, kept as it scales" },
        { token: "--tick-radius", value: lookOf("TIK.001").corners, code: "TIK.001", what: "the corners of a tick box" },
        { token: "--fold-arrow-size", value: px(lookHeight("ARW.002")), code: "ARW.002", what: "the fold arrow of a card" },
        { token: "--card-symbol-size", value: px(lookHeight("SYM.001")), code: "SYM.001", what: "the symbol on a card tile" }
    ];
    const problems: string[] = [];
    for (const [token, codes] of SAME) {
        const base = tokens.find(t => t.token === token)!;
        for (const code of codes) if (px(lookHeight(code)) !== base.value) problems.push(token + ": " + code + " is " + lookHeight(code) + "px in the library, not " + base.value);
    }
    if (problems.length) throw new Error(problems.join("\n"));
    return tokens;
}

/** The text of src/styles/components.generated.css. */
export function renderComponentTokens(): string {
    const out = [
        "/* Generated by tools/scripts/library/component-tokens.mjs from the library (src/library/data/library.ts).",
        "   Do not edit this file: change the look in the library and run `npm run library:tokens`. */",
        "",
        ":root {",
        ""
    ];
    for (const t of componentTokens()) out.push("    /* " + t.what + " (" + t.code + ") */", "    " + t.token + ": " + t.value + ";", "");
    out.push("}", "");
    return out.join("\n");
}
