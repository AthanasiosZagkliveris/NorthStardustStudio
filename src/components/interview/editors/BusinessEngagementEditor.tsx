import { CSSProperties, ReactNode } from "react";
import CardShell from "../cards/CardShell.tsx";
import { BUSINESS_JOURNEY_STAGES, BUSINESS_RELATIONSHIP_TYPES, segmentHue } from "../../../framework/engine/AnswerUtils.ts";
import { demandResult } from "../../../framework/engine/DemandCapacity.ts";
import SectionTiles, { DialogHeading, OPEN_EVENT, type ItemMark, type OpenRequest, type SectionTile } from "../tiles/SectionTiles.tsx";
import type { TileAdd } from "../tiles/SectionTileTypes.ts";
import { DEMAND_BLOCK_HELP } from "./engagement/shared.tsx";
import CardBoxes, { type CardBox } from "../cards/CardBoxes.tsx";
import { BusinessEmpty } from "../cards/BusinessCardFields.tsx";
import FoldAllToggle from "../fields/FoldAllToggle.tsx";
import { ActionPicker } from "./ChannelResources.tsx";
import { IsolationNote } from "./ActionMarkers.tsx";
import FoldArrow from "../fields/FoldArrow.tsx";
import { SECTIONS, segmentQuestions } from "./BusinessEngagementModel.ts";
import "../../../styles/demand.css";
import { BusinessEngagementEditorProps } from "./engagement/shared.tsx";

import { useEngagementState } from "./engagement/useEngagementState.tsx";
import { useEngagementChannelBoxes } from "./engagement/useEngagementChannelBoxes.tsx";
import { useEngagementRelationships } from "./engagement/useEngagementRelationships.tsx";
import { useEngagementDemand } from "./engagement/useEngagementDemand.tsx";

export default function BusinessEngagementEditor(props: BusinessEngagementEditorProps) {

    const part1 = useEngagementState(props);
    const part2 = { ...part1, ...useEngagementChannelBoxes({ ...part1 }) };
    const part3 = { ...part1, ...part2, ...useEngagementRelationships({ ...part1, ...part2 }) };
    const part4 = { ...part1, ...part2, ...part3, ...useEngagementDemand({ ...part1, ...part2, ...part3 }) };
    const { addCustomerSource, addSuggestedSource, suggestedSources, addRelationshipType, typeOf, profilesOf, scopeChoice, showsAll, asTiles, channelCategoryFoldKeys, channelResourceTable, channelTiles, channelViewChoice, channelsFor, clearIsolation, collapsed, columnsDivider, demandFor, engagement, engagedOfferingIds, foldingSection, folds, heads, isolated, isolationNames, offeringRelationshipsOf, referenceColumn, relationshipsFor, segmentOf, segments, toggle } = part4;

    /*
        THE PAGE AS TILES (doc 47, section 3, step one): one chapter per Segment, in the Segment's colour, as Page 1's, holding three Master Tiles -- Channels and
        Journey, Customer's Relationship, Demand & Conversion (the channel expenses are the Inventory's: owner, 2026-11-12 19:54). Each opens its section in a dialog;
        the section's help is the "i" beside the dialog's heading; each dialog's head says what it offers, From your answers or All (ScopeChoice). No saved key changes.
    */
    if (asTiles && segments.length > 0) {

        /* A face's line of two columns: a name and its figure, the figure in bold (as the Financial Foundation's). */
        const pair = (name: string, figure: string) => name + "\u0001" + (figure ? "**" + figure + "**" : "");
        const offeringName = (segment: (typeof segments)[number], offeringId: string) =>
            segment.offerings.find(offering => offering.id === offeringId)?.name.trim() || "Offering";

        const tilesOf = (segment: (typeof segments)[number]): SectionTile[] => {
            const answers = segmentOf(segment.id);
            const offeringIds = engagedOfferingIds(segment);
            const hue = segmentHue(segment);
            const dialog = (title: string, info: readonly string[] | undefined, body: ReactNode, extra?: ReactNode) => (
                <div className="column-tile-content" style={{ "--strategy-theme-hue": hue } as CSSProperties}>
                    <div className="business-engagement-section-head">
                        <DialogHeading title={title} info={info ? [...info] : undefined} />
                    </div>
                    {/* (Its choices under the heading, in a row: the Inventory's bar, its radios.) */}
                    {extra && <div className="capability-overview-bar">{extra}</div>}
                    {body}
                </div>
            );
            /* ONE CARD TILE PER OFFERING (owner, 2026-11-12 17:33: "autogenerated tiles per offering"): made from Page 1's Offerings, in their order; pressing one opens
               that Offering's own block as a floating card. The ids are kept apart per tile (`rel:`, `dem:`), so a card asked for by id opens in its own tile. */
            const relTypes = (offeringId: string) => offeringRelationshipsOf(segment.id, offeringId).types
                .map(type => BUSINESS_RELATIONSHIP_TYPES.find(entry => entry.id === type)?.label ?? "").filter(label => label !== "");
            const expected = (offeringId: string) => {
                const result = demandResult(engagement.demand[offeringId]);
                return result.expected === null ? "" : result.recurring ? result.expected + " active" : result.expected + " a month";
            };
            // (An Offering's tile: its lines, their marks, and -- with All -- its "+", which adds to it and opens its card.)
            const offeringBoxes = (prefix: string, lines: (offeringId: string) => string[], marks?: (offeringId: string) => ItemMark[], plus?: { what: string; add: (offeringId: string) => boolean | void }): CardBox[] => offeringIds.map((offeringId, at) => ({
                id: prefix + offeringId,
                number: at + 1,
                name: offeringName(segment, offeringId),
                unnamed: "Offering",
                lines: lines(offeringId),
                marks: marks?.(offeringId),
                own: true,
                plus: plus && showsAll(segment.id) ? {
                    what: plus.what,
                    disabled: false,
                    onAdd: () => {
                        if (plus.add(offeringId) !== false) {
                            window.setTimeout(() => document.dispatchEvent(new CustomEvent<OpenRequest>(OPEN_EVENT, { detail: { tile: segment.id + (prefix === "rel:" ? ":relationships" : ":demand"), card: prefix + offeringId } })), 80);
                        }
                    }
                } : undefined,
                content: () => null
            }));
            // (Under the Offering's name on its relationship tile, the Profiles it serves, then its relationship types: owner, 2026-11-12 19:54.)
            // (The Offering's types: those its answers create and those the founder added -- relationshipTypesOf; no suggestion is left to show; owner, 2026-11-13 00:31.)
            const relLines = (offeringId: string) => [...profilesOf(segment, offeringId).map((profile, at) => profile.name.trim() || "Profile " + (at + 1)), ...relTypes(offeringId)];
            const relMarks = (offeringId: string): ItemMark[] => [...profilesOf(segment, offeringId).map(() => ({ plain: true })), ...relTypes(offeringId).map(() => ({ bullet: true }))];
            // (An Offering's tile in Demand & Conversion: its expected sales, then, faded, the sources the Foundation suggests; pressing one adds it, with its channel,
            // and opens the card -- the add on the tile; owner, 2026-11-12 23:16.)
            const demLines = (offeringId: string) => [...(expected(offeringId) ? [expected(offeringId)] : []), ...suggestedSources(segment, offeringId).map(row => "Suggested: " + row.words)];
            const demMarks = (offeringId: string): ItemMark[] => [...(expected(offeringId) ? [{ bullet: true }] : []), ...suggestedSources(segment, offeringId).map(() => ({ bullet: true, empty: true }))];
            const demBoxes = (): CardBox[] => offeringBoxes("dem:", demLines, demMarks, { what: "Customer Source", add: addCustomerSource }).map(box => {
                const offeringId = box.id.slice(4);
                const rows = suggestedSources(segment, offeringId);
                if (rows.length === 0) {
                    return box;
                }
                const first = demLines(offeringId).length - rows.length;
                return {
                    ...box,
                    linkedLines: demLines(offeringId).map((_line, at) => at >= first),
                    onLine: (at: number) => {
                        const row = rows[at - first];
                        if (row) {
                            addSuggestedSource(offeringId, row);
                            window.setTimeout(() => document.dispatchEvent(new CustomEvent<OpenRequest>(OPEN_EVENT, { detail: { tile: segment.id + ":demand", card: box.id } })), 80);
                        }
                    }
                };
            });
            /*
                A TILE THAT HOLDS SEVERAL CARDS OPENS A DIALOG OF THEM (owner, 2026-11-13 04:58: "Tiles that could contain more than one floated card, should also open to
                dialogue cards"): each Offering is a tile -- its Profiles under its name, then its relationship types --, opening a dialog of a card tile per type (and,
                with All, the Add Card tile); each type's tile opens that type's card. As a channel's tile opens its subchannels.
            */
            const typeCardId = (offeringId: string, typeId: string) => "relt:" + offeringId + "|" + typeId;
            const typeLabel = (typeId: string) => BUSINESS_RELATIONSHIP_TYPES.find(entry => entry.id === typeId)?.label ?? "Relationship Type";
            const relTiles = (): SectionTile[] => offeringIds.map((offeringId, at) => {
                const types = offeringRelationshipsOf(segment.id, offeringId).types;
                const profiles = profilesOf(segment, offeringId);
                const name = offeringName(segment, offeringId);
                const add: TileAdd | undefined = showsAll(segment.id) && types.length < BUSINESS_RELATIONSHIP_TYPES.length ? {
                    label: "Relationship Type",
                    disabled: false,
                    onAdd: () => typeCardId(offeringId, addRelationshipType(segment, offeringId)),
                    // (A type added is never blank: it has its stages and its fields at once.)
                    isBlank: () => false,
                    onRemove: () => undefined
                } : undefined;
                return {
                    id: segment.id + ":rel:" + offeringId,
                    // (Numbered as the Offering's tile in Demand & Conversion.)
                    title: (at + 1) + ". " + name,
                    view: true,
                    // (A type's card, opened from the Offering's dialog, carries no box name: the dialog's heading says it.)
                    bareCards: true,
                    items: relLines(offeringId),
                    itemMarks: relMarks(offeringId),
                    links: [...profiles.map(() => undefined), ...types.map(typeId => ({ card: typeCardId(offeringId, typeId) }))],
                    holds: types.map(typeId => typeCardId(offeringId, typeId)),
                    add,
                    cardFor: (id: string) => {
                        const typeId = id.startsWith("relt:" + offeringId + "|") ? id.slice(("relt:" + offeringId + "|").length) : "";
                        return types.includes(typeId) ? floatingOf(relationshipsFor(segment, offeringId, true, typeId)) : null;
                    },
                    content: () => dialog(name, SECTIONS.relationships.instructions.slice(0, 3), (
                        <CardBoxes
                            label={"Relationship types of " + name}
                            what="Relationship Type"
                            autoStart={false}
                            add={add}
                            items={types.map((typeId, at) => ({
                                id: typeCardId(offeringId, typeId),
                                number: at + 1,
                                name: typeLabel(typeId),
                                unnamed: "Relationship Type",
                                // (Its Purpose, the line that says what it is for.)
                                lines: typeOf(segment.id, offeringId, typeId).purpose.trim() ? [typeOf(segment.id, offeringId, typeId).purpose.trim()] : [],
                                own: true,
                                content: () => null
                            }))}
                        />
                    ))
                };
            });
            const offeringOf = (id: string) => id.slice(4);
            // (The card is its own shell, BusinessCard, straight in the content: the floating card styles of the Foundation's cards reach it.)
            const floatingOf = (body: ReactNode) => <div className="column-tile-content" style={{ "--strategy-theme-hue": hue } as CSSProperties}>{body}</div>;

            return [
                {
                    id: segment.id + ":channels",
                    // (Its title on two lines, as a Master Tile's long title is: layout rules 9, "A title with a forced break"; owner, 18:41.)
                    title: "Channels and\nJourney",
                    // (The chapter's three Master Tiles keep the size of a 2 x 2 chapter's, two to a row, as Page 1's: layout rules 9, "Large tiles".)
                    large: true,
                    anchor: "engagement-section-" + segment.id + "-channels",
                    // The five stages, each with the number of channels used at it.
                    items: BUSINESS_JOURNEY_STAGES.map(stage => pair(stage.label, String(answers.channels.filter(channel => channel.stages.includes(stage.id)).length))),
                    content: () => dialog("Channels and Journey", [...SECTIONS.channels.instructions, "Faded channels and subchannels stand ready to add: those your Foundation answers suggest list what they suggest, and pressing any of them adds it.", "Place the tiles by Channels, or by Journey Stages to see the subchannels used at each stage."], channelTiles(segment), (
                        // (The choice of how the tiles are placed, then the isolation note while one stands.)
                        <>
                            {channelViewChoice(segment)}
                            {scopeChoice(segment.id)}
                            {isolated && isolated.segmentId === segment.id && <IsolationNote kind={isolated.kind === "action" ? "shared" : "linked"} names={isolationNames()} onClear={clearIsolation} />}
                        </>
                    ))
                },
                {
                    id: segment.id + ":relationships",
                    title: "Customer's\nRelationship",
                    large: true,
                    anchor: "engagement-section-" + segment.id + "-relationships",
                    // Each Offering with its relationship types.
                    items: offeringIds.map(offeringId => pair(offeringName(segment, offeringId), offeringRelationshipsOf(segment.id, offeringId).types
                        .map(type => BUSINESS_RELATIONSHIP_TYPES.find(entry => entry.id === type)?.label ?? "").filter(label => label !== "").join(", "))),
                    group: "Customer's Relationship",
                    content: () => dialog("Customer's Relationship", SECTIONS.relationships.instructions.slice(0, 3), offeringIds.length > 0
                        ? <SectionTiles label={"Customer's Relationship of " + (segment.name.trim() || "this Segment")} hue={segmentHue(segment)} tiles={relTiles()} />
                        : relationshipsFor(segment), scopeChoice(segment.id))
                },
                {
                    id: segment.id + ":demand",
                    title: "Demand &\nConversion",
                    large: true,
                    anchor: "engagement-section-" + segment.id + "-demand",
                    // Each Offering with its expected sales a month (active clients for a recurring one).
                    items: offeringIds.map(offeringId => {
                        const result = demandResult(engagement.demand[offeringId]);
                        return pair(offeringName(segment, offeringId), result.expected === null ? "" : result.recurring ? result.expected + " active" : result.expected + " a month");
                    }),
                    group: "Demand & Conversion",
                    bareCards: true,
                    holds: offeringIds.map(offeringId => "dem:" + offeringId),
                    cardFor: (id: string) => offeringIds.includes(offeringOf(id)) ? floatingOf(demandFor(segment, offeringOf(id), offeringName(segment, offeringOf(id)), true)) : null,
                    content: () => dialog("Demand & Conversion", [SECTIONS.relationships.instructions[3], ...DEMAND_BLOCK_HELP.map(point => typeof point === "string" ? point : "")].filter(Boolean) as string[], (
                        <CardBoxes items={demBoxes()} label={"Demand & Conversion of " + (segment.name.trim() || "this Segment")} what="Offering" autoStart={false} />
                    ), scopeChoice(segment.id))
                }
            // (Channel Costs is no tile of its own: the channel expenses are the Inventory's, its Channel Costs set-up; owner, 2026-11-12 19:54.)
            ];
        };

        return (
            <div className="answer-columns business-foundation business-engagement business-capability column-tiles-page" style={{ "--answer-column-count": 1 } as CSSProperties}>
                {/* A resource waiting for one of its channel's actions: the table's action lines take a click. */}
                <ActionPicker />
                <div className="business-foundation-segment-frames">
                    {segments.map((segment, index) => {
                        const name = (segments.length > 1 ? (index + 1) + ". " : "") + (segment.name.trim() || "Segment");
                        return (
                            <CardShell
                                key={segment.id}
                                data-anchor={"engagement-segment-" + segment.id}
                                style={{ "--strategy-theme-hue": segmentHue(segment) } as CSSProperties}
                            >
                                <div className="card-scroll">
                                    <div className="business-capability-section business-capability-tiles-section">
                                        {/* The Segment's chapter, named as on Page 1 (its name is edited there). */}
                                        <div className="business-engagement-section-head tiles-frame-head"><span className="field-group-title business-foundation-subhead">{name}</span></div>
                                        <SectionTiles label={name + ": Channels and Journey, Customer's Relationship, Demand & Conversion"} hue={segmentHue(segment)} tiles={tilesOf(segment)} />
                                    </div>
                                </div>
                            </CardShell>
                        );
                    })}
                </div>
            </div>
        );

    }

    return (

        <div
            className="answer-columns business-foundation business-engagement"
            style={{ "--answer-column-count": 2 } as CSSProperties}
        >

            {/* A resource waiting for one of its channel's actions: the table's action lines take a click. */}
            <ActionPicker />

            {/* Row 1: the two section titles. */}
            {/* (As tiles, each section carries its own title inside the Segment's frame: the same two titles are not said again above it.) */}
            {!asTiles && heads.map(head => (
                <h3 className="answer-column-label" key={"title-" + head.number}>
                    <span className="answer-column-label-number">
                        {head.number + "."}
                    </span>
                    <span className="answer-column-label-text">{head.title}</span>
                </h3>
            ))}

            {/* Row 3: the process line, the boundary between what
                the page says and what it asks. */}
            {columnsDivider && (
                <div className="answer-columns-divider">
                    {columnsDivider}
                </div>
            )}

            {/* Row 4: ONE INPUT CARD PER SEGMENT, in the Segment's
                own colour -- Page 1's card, continued.

                Both sections are answered about a Segment, so a
                Segment is what a card holds: the Foundation it
                refers to, the channels that reach it, and the
                relationships kept with its Profiles. */}
            {segments.length === 0 ? (
                <div className="business-engagement-page-empty">
                    <BusinessEmpty>
                        Define a Customer Segment on the Foundation page first.
                        Everything on this page is answered about one.
                    </BusinessEmpty>
                </div>
            ) : segments.map((segment, segmentIndex) => {

                const key = "engagement-" + segment.id;

                const open = !collapsed.has(key);

                const segmentArrow = (
                    <FoldArrow
                        open={open}
                        label={"Segment " + (segmentIndex + 1)}
                        onToggle={() => toggle(key)}
                    />
                );

                return (
                    <CardShell
                        
                        key={segment.id}
                        data-anchor={"engagement-segment-" + segment.id}
                        role="group"
                        aria-label={"Segment " + (segmentIndex + 1) + ": " +
                            (segment.name.trim().length > 0 ? segment.name.trim() : "Not named yet")}
                        /* The Segment's OWN colour, chosen on Page 1
                           and carried here: the same Segment is the
                           same colour on both pages, which is most
                           of what makes this read as the next page
                           rather than a different feature. */
                        style={{ "--strategy-theme-hue": segmentHue(segment) } as CSSProperties}
                    >

                        {/* NO HEAD ROW OF ITS OWN: the card's fold arrow
                            stands next to "1. SEGMENT", the first
                            column's heading, in the card's arrow
                            column. Folded, that heading stands alone
                            with the Segment's name, as a folded card
                            shows its name. */}
                        {open ? (
                            <div className="business-engagement-references">

                                <div className="business-engagement-reference-columns">

                                    {referenceColumn(
                                        "Segment",
                                        "Segment",
                                        segmentQuestions,
                                        [{
                                            key: segment.id,
                                            name: segment.name,
                                            description: segment.description
                                        }],
                                        true,
                                        segmentIndex + 1,
                                        segmentArrow
                                    )}

                                    {referenceColumn(
                                        "Profiles",
                                        "Profile",
                                        () => SECTIONS.channels.profileInformation,
                                        segment.profiles.map(profile => ({
                                            key: profile.id,
                                            name: profile.name,
                                            description: profile.description
                                        })),
                                        true
                                    )}

                                    {referenceColumn(
                                        "Offerings",
                                        "Offering",
                                        () => SECTIONS.channels.offeringInformation,
                                        segment.offerings.map(offering => ({
                                            key: offering.id,
                                            name: offering.name,
                                            description: offering.description
                                        })),
                                        true
                                    )}

                                </div>

                            </div>
                        ) : (
                            <div className="business-engagement-references business-engagement-segment-folded">
                                <span className="business-foundation-label-info">
                                    <span className="field-group-title business-foundation-subhead">
                                        {segmentArrow}
                                        <span className="business-engagement-reference-number">
                                            {(segmentIndex + 1) + "."}
                                        </span>
                                        Segment
                                    </span>
                                </span>
                                <span className="strategy-name-static">
                                    {segment.name.trim().length > 0
                                        ? segment.name
                                        : "Not named yet"}
                                </span>
                            </div>
                        )}

                        {open && (
                        <>

                                {/* Each section folds away. Both of
                                    them run to a table, and a founder
                                    working on one has no use for the
                                    other underfoot. */}
                                {foldingSection(
                                    segment.id + "-channels",
                                    "1. Customer Channel",
                                    () => (
                                        <>
                                            {asTiles ? channelTiles(segment) : channelsFor(segment)}
                                            {channelResourceTable(segment)}
                                        </>
                                    ),
                                    0,
                                    <>
                                        {isolated && isolated.segmentId === segment.id && (
                                            <IsolationNote
                                                kind={isolated.kind === "action" ? "shared" : "linked"}
                                                names={isolationNames()}
                                                onClear={clearIsolation}
                                            />
                                        )}
                                        <FoldAllToggle
                                            ids={channelCategoryFoldKeys(segment.id)}
                                            folds={folds}
                                            label="channel categories"
                                        />
                                    </>
                                )}

                                <>
                                {foldingSection(
                                    segment.id + "-relationships",
                                    "2. Customer Relationship",
                                    () => relationshipsFor(segment),
                                    1,
                                    <FoldAllToggle
                                        ids={engagedOfferingIds(segment).map(
                                            offeringId => "relationship-offering-" + offeringId
                                        )}
                                        /* Cascades into each Offering's
                                           Demand & Conversion block. */
                                        nested={engagedOfferingIds(segment).map(
                                            offeringId => "demand-" + offeringId
                                        )}
                                        folds={folds}
                                        label="offerings"
                                    />
                                )}

                                {/* DEMAND & CONVERSION, a section of its own after the table: for each Offering, how its customers come, and so how many sales to expect. */}
                                {foldingSection(
                                    segment.id + "-demand",
                                    "3. Demand & Conversion",
                                    () => (
                                        <div className="business-demand-section">
                                            {engagedOfferingIds(segment).map(offeringId => (
                                                <div className="business-demand-cell" key={offeringId} data-anchor={"demand-section-" + offeringId}>
                                                    {demandFor(segment, offeringId, segment.offerings.find(offering => offering.id === offeringId)?.name.trim() || "Offering")}
                                                </div>
                                            ))}
                                        </div>
                                    ),
                                    1
                                )}
                                </>
                        </>
                        )}

                    </CardShell>
                );

            })}

        </div>

    );

}
